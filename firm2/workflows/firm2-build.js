// Сверка целостности переданного `args` (Д-23 проект-В 29.10.2026). Передать вывод
// `build-args` сборщику можно только вставкой в вызов — путь к файлу Workflow не
// принимает, — а вывод этот на живой поставке 47 КБ. Маршрут велит «руками ничего не
// составляй», но исполнимого пути под это правило нет, и на проект-В Оркестратор
// сократил: обрезал `last_verdict.notes` у трёх задач и обнулил у одной список из
// двадцати критериев. Прогон запустился и выглядел нормальным. Между тем
// `last_verdict.notes` уходит в промпт стадии ДОСЛОВНО (см. ниже, dev-промпт):
// Разработчик получил бы пересказ вердикта вместо самого вердикта — на задаче,
// которую за эти критерии и эскалировали.
//
// Поэтому прогон останавливается ЗДЕСЬ, до первой стадии: ни одно событие ещё не
// написано, ни одно дерево не создано, и повторная вставка ничего не стоит. Падение
// после открытия стадии стоило бы дорого — и тем самым подталкивало бы обойти сверку.
const INTEGRITY = ARGS.integrity || null
if (INTEGRITY) {
  const got = { tasks: TASKS.length, verdict_criteria: 0, verdict_chars: 0 }
  for (const t of TASKS) {
    const v = t && t.last_verdict
    if (!v) continue
    got.verdict_criteria += Array.isArray(v.criteria) ? v.criteria.length : 0
    got.verdict_chars += String(v.notes || '').length
  }
  // Текст решения разбора — свой счётчик (Д-27): он из другого события и сокращается
  // отдельно. Ключа нет (вывод прежней версии движка) — счётчик не сверяется.
  if (Object.prototype.hasOwnProperty.call(ARGS.integrity || {}, 'arbitration_chars')) {
    got.arbitration_chars = 0
    for (const t of TASKS) {
      if (t && t.last_arbitration) got.arbitration_chars += String(t.last_arbitration.notes || '').length
    }
  }
  const bad = Object.keys(got).filter((k) => Number(INTEGRITY[k]) !== got[k])
  if (bad.length) {
    throw new Error(
      'args приехал не целиком: ' +
        bad.map((k) => `${k} — движок насчитал ${INTEGRITY[k]}, в args ${got[k]}`).join('; ') +
        '. Прогон остановлен ДО первой стадии: ни одного события не написано. ' +
        'Нужно передать вывод `firm-state.mjs build-args` заново и ЦЕЛИКОМ, не сокращая ' +
        'ни одного поля: `last_verdict.notes` и `criteria` уходят в промпт стадии дословно. ' +
        'Удобнее через файл: `build-args --out <файл>`, затем вставить содержимое файла.',
    )
  }
}

