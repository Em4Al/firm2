// `sleep`-опроса, потому что в ХОЛОДНОМ дереве тот же набор идёт больше часа против семи
// минут на прогретом HEAD. И ровно та же точка ветвления (c24952f) была независимо
// измерена стадией T-181 — две стадии платили за один коммит.
