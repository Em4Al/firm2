// Склонение числительных. Своё, потому что у workflow нет ни импортов, ни доступа к ФС
// (ADR-0002, поправка 21.09.2026): скрипт исполняется как тело функции, и `lib/firm.mjs`
// ему недоступен. Правило русское, обычное: 1 файл, 2 файла, 5 файлов.
function plural(n, one, few, many) {
  const a = Math.abs(Number(n) || 0) % 100
  const b = a % 10
  if (a > 10 && a < 20) return many
  if (b > 1 && b < 5) return few
  if (b === 1) return one
  return many
}

