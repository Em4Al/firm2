//
// Разбор 30.10.2026 (проект-В, волна из 62 стадий). Промпт Тестировщика велел прогнать
// набор на merge-base самому — «запомни список красных», — и роли это исполняли буквально:
// заводили своё дерево на точке ветвления, прилинковывали туда `node_modules` руками и
