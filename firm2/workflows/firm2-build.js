// доезжала. Одна названная причина полезнее восьми повторов слова «неизвестно» (И-12).
const BASE_FAIL = new Map()
// Зонды основания выстроены В ОЧЕРЕДЬ, и это не перестраховка. Задачи волны идут
// параллельно, их стадии теста начинаются почти одновременно, и без очереди все три
// спросили бы основание разом — то есть каждая получила бы пустой список уже измеренных
