// ── Планировщик (§3.3, §4) ────────────────────────────────────────────────────
// Код, а не модель, решает: что готово к запуску, сколько потоков занято и
// пускать ли задачу, не помеченную parallel_safe (такая идёт одна).

// Карман шага слияния, который не свёлся обратно (Д-34). Пока он лежит, главное дерево
// стоит с несведённым индексом, и git отказывается НАЧИНАТЬ любое слияние — то есть
// следующая задача падает на чужом конфликте и с собственным именем в событии. Поэтому
// признак глобальный: прогон доводит начатое и больше не вливает ничего.
let POCKET = null

// Слияния выстроены В ОЧЕРЕДЬ, и довод тот же, что у зондов основания: они идут в ГЛАВНОМ
// дереве, одном на весь прогон. Два мержа разом — это две правки индекса одного дерева,
// то есть состояние, в котором ни один из них не может честно ответить, что он застал.
// Очередь заодно и делает признак кармана (Д-34) действенным: остановить можно только то,
// что ещё не началось, а при параллельных задачах слияние соседней уже шло бы.
let MERGE_CHAIN = Promise.resolve()
function mergeQueued(task, ports) {
  // `skipped` — не отказ слияния, а «не начинали»: при несведённом индексе git мерж и не
  // начнёт, и записывать задаче merge/failed было бы неправдой.
  const call = async () => {
    if (POCKET) return { status: 'skipped' }
    const m = await mergeTicket(task, ports)
    // Признак поднимается ЗДЕСЬ, а не у вызывающего: между возвратом мержа и строкой в
    // `runOne` стоит микрозадача, и следующий в очереди успевал проскочить в неё.
    if (m && m.pocket_conflict) {
      POCKET = { id: task.id, files: Array.isArray(m.pocket_files) ? m.pocket_files : [] }
    }
    return m
  }
  const next = MERGE_CHAIN.then(call, call)
  MERGE_CHAIN = next.then(() => {}, () => {})
  return next
}

