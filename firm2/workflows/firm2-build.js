// `agent_id` в полезной нагрузке хука есть всегда. Разбор — `markerFromAgent` в
// lib/firm.mjs, достройка при чтении журнала — `resolveFromTranscripts` там же.

// Коммит — последний шаг стадии, и он обязателен.
//
// Дефект обкатки на проект-В 01.10.2026, системный: из шести багов поставки ЧЕТЫРЕ — один и
// тот же промах, «стадия написала тест и не закоммитила». Четыре задачи из восьми ушли на
// лишнюю попытку, то есть полный цикл Dev → Test → ревью прогонялся заново не из-за кода.
//
// Почему именно так ломалось. Ревьюер-QA судит по ветке и диффу; файл в рабочем каталоге
// для него не существует, и вердикт выходит «тестов нет» при пятистах строках тестов на
// диске. Слияние потом подобрало бы хвост (ШАГ 1 в mergeTicket), но до слияния дело не
// доходит: отклонённая задача туда не попадает вовсе.
//
// Промпту Разработчика про коммит говорила одна фраза в конце, а промпту Тестировщика —
// ничего. Теперь обоим говорится одинаково и командой, а признак законченности назван
// проверяемый: пустой `git status --short`.
function commitRule(task, kind) {
  const wt = worktreeOf(task)
  const where = wt ? ` -C ${wt}` : ''
  return (
    `\nПОСЛЕДНИЙ ШАГ СТАДИИ — коммит. Стадия не закончена, пока написанное не в ветке:\n` +
    `  git${where} status --short        # СНАЧАЛА посмотри, что добавляешь\n` +
    `  git${where} add -- <свои файлы по именам>\n` +
    `  git${where} commit -m "${kind}(${task.id}): <что сделано>"\n` +
    `  git${where} status --short        # своего незакоммиченного остаться не должно\n` +
    `\`add -A\` НЕ использовать: он забирает и то, чего ты не писал. Разбор проект-В 11.10.2026 — ` +
    `профиль Chrome, оставленный проверкой СОСЕДНЕЙ задачи (296 файлов, 4,1 МБ), уехал в коммит ` +
    `стадии, где настоящих правок было четыре файла, и они в нём утонули.\n` +
    `Ревьюер-QA судит по ветке task/${task.id} и диффу, а не по твоему рабочему каталогу: ` +
    `незакоммиченный файл для него не существует, и вердикт будет «не сделано» при ` +
    `готовой работе на диске. Непустой status — незаконченная стадия, а не мелочь на потом.\n`
  )
}

// Предел, который агент может соблюсти сам. Жёсткого таймаута у стадии нет и быть не
// может: `agent()` в Workflow не принимает ни таймаута, ни отмены, а убитая на середине
// стадия оставила бы недописанное рабочее дерево без события финиша — хуже, чем дать ей
// доработать. Поэтому предел ставится не часами снаружи, а признаком изнутри: агент видит
// не минуты, а свои попытки, и «третий заход на ту же ошибку» он распознаёт надёжно, в
// отличие от «прошло двадцать пять минут».
//
// Эскалация тут не поражение, а штатный ход маршрута: `escalate: true` возвращает задачу
// в арбитраж (§3 команды), где решение принимает Архитектор или человек. Дорого не
// признать тупик, а молча ходить по кругу на Opus.
function limitLine() {
  return (
    `Предел работы. Если один и тот же подход не сошёлся ТРИЖДЫ — та же ошибка, тот же ` +
    `красный тест, тот же тупик, — не заходи на четвёртый. Верни escalate: true и опиши в ` +
    `notes: что пробовал, на чём споткнулся и какого решения не хватает. Это штатный ход, ` +
    `а не провал: задачу разберёт арбитраж. Молчаливый четвёртый заход хуже честной ` +
    `остановки — он стоит денег и не кончается.\n`
  )
}

