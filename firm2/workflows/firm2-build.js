// Короткая полоса: заслужила ли задача пропуск стадий надзора.
//
// Замер проект-В: T-088 снимала строку пояснения и ключ словаря — разработка 41 секунда,
// тестирование 24 минуты 36 секунд с +175 строками новых тестов. Проект завёл правило
// BR-138 и исполнял его РУКАМИ, в обход движка: стадии не открывались, события не писались,
// и такая работа выглядела в журнале пропавшей.
//
// Два решения держат полосу честной:
//   • метку ставит ПЛАНИРОВАНИЕ (Архитектор), а не исполнитель стадии — иначе работу
//     классифицирует тот, кто ещё её не сделал;
//   • метка — лишь ЗАЯВКА: судит её код по настоящему диффу ветки задачи. Вышел за
//     разрешённые пути — полоса отменяется и задача идёт полным циклом. Без этой
//     проверки короткая полоса стала бы четвёртым способом пройти проверку, не выполнив
//     её, рядом с пропуском теста и ожидаемым падением.
//
// Направление отказа — закрытое (И-12): зонд не ответил → полного цикла. Цена ошибки в
// эту сторону — одна лишняя пара стадий; в обратную — принятая без надзора правка логики.
async function laneState(task) {
  // Направление отказа закрытое и здесь: сорвался зонд — полоса не заслужена, идёт
  // полный цикл. Цена ошибки в эту сторону — лишняя пара стадий.
  return tryCall(`полоса:${task.id}`, () => laneStateOnce(task), null, task.id)
}

async function laneStateOnce(task) {
  if (!(task.labels || []).includes(SHORT_LANE_LABEL)) return null
  // Тай-брейк: метка безопасности отменяет короткую полосу, сколько бы мелким дифф ни
  // выглядел. Приём взят у ECC («тронул security-триггер — не ниже standard»), и он
  // закрывает единственный способ обойти панель безопасности законной меткой: поставить
  // рядом `короткая-полоса` и уложиться в пути. Две метки вместе — это противоречие
  // заявок, и разрешается оно в сторону проверки.
  if ((task.labels || []).includes(SECURITY_LABEL)) {
    log(
      `Задача ${task.id}: метки «${SHORT_LANE_LABEL}» и «${SECURITY_LABEL}» стоят вместе — ` +
        'полоса отменена, идёт полный цикл с панелью. Триггер безопасности сильнее размера правки.',
    )
    return null
  }
  if (!LANE_PATHS.length) {
    log(
      `Задача ${task.id}: метка «${SHORT_LANE_LABEL}» стоит, но ключа short_lane.paths в ` +
        '.firm/config нет — движок не знает, какие пути считать текстом. Полный цикл.',
    )
    return null
  }
  if (!PLUGIN_ROOT) return null
  const r = await agent(
    `Выполни ровно одну команду и верни её результат:\n` +
      `  node "${PLUGIN_ROOT}/scripts/firm-state.mjs" lane-check --ticket ${task.id} --json\n` +
      `Ответ — JSON с полями verdict и why.\n` +
      `Верни { state: "ok", verdict: <verdict как есть>, why: <why как есть> }.\n` +
      `Команда не запустилась, упала или ответила не-JSON → { state: "unknown" } и положи ` +
      `в output то, что увидел. Своего мнения о задаче не высказывай: заслуженность полосы ` +
      `решает команда, ты её перо.\n` +
      `Ничего не меняй, других команд не выполняй.`,
    { agentType: A.devops, ...on('devops'), schema: LANE_SCHEMA, label: `полоса:${task.id}`, phase: 'Build' },
  )
  if (!r || r.state !== 'ok') {
    log(`Задача ${task.id}: проверить короткую полосу не удалось (${(r && r.output) || '—'}) → полный цикл`)
    return null
  }
  return r
}

