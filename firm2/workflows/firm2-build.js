// снимает его движок, один раз на sha, в постоянном тёплом дереве `_base` (прогрев —
// `node_modules`, кэши — стоит дороже самого прогона и потому не выбрасывается), и
// выдаёт стадиям как данность. Сколько задач волны ответвились от одного коммита —
// столько раз мы НЕ платим.
//
// Отказ открытый, как и у `trunkRed`: не снялось — стадиям сказано, что второй половины
// у них нет, и выдавать свою сверку за полный ответ нельзя. Молчать нельзя, блокировать
