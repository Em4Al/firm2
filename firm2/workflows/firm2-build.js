// разбор проект-В 13.10.2026 (Д-8.5) показал, что случай шире браузера: прогон отчитался
// «чисто, ничего не требует очистки», а в каталоге рабочих деревьев лежало 377 МБ — из них
// 150 МБ копия репозитория `_t101-probe`, сделанная ролью ради замера, и 26 МБ копия
// `.base-T071-review`, сделанная ревьюером. Ни ту, ни другую `git worktree prune` не видит:
// это не рабочие деревья, а обычные каталоги рядом.
//
// Лечится промптом, а не кодом: сносить чужие каталоги движок не вправе (внутри может быть
// работа человека), он их теперь только называет с размером — `firm-state.mjs orphans`,
// поле `strays`. Поэтому правило адресовано тому, кто каталог создаёт.
function scratchRule(task) {
  const wt = worktreeOf(task)
  return (
    `РАБОЧИЕ КОПИИ И ЗАМЕРЫ — В $TMPDIR, абсолютным путём. Нужна копия репозитория, ` +
    `второй чекаут, каталог под замер, кеш сборки — делай их в $TMPDIR и убирай за собой, ` +
    `НИКОГДА не рядом с ${wt ? `деревом задачи (${wt})` : 'рабочим деревом задачи'} и не ` +
    `внутри него. Каталог рядом переживает уборку: git его деревом не считает, ` +
    `\`worktree prune\` не видит, и он остаётся на диске до следующего разбора — на проект-В ` +
    `так накопилось 377 МБ, из них одна копия ради замера весила 150 МБ.\n`
  )
}

function marks(task, attempt) {
  return (
    `FIRM2-CHANGE: ${CHANGE}\n` +
    `FIRM2-TICKET: ${task.id}\n` +
    `FIRM2-ATTEMPT: ${attempt}\n` +
    // Промпты ролей ссылаются на `$ENGINE/...` (памятка по линту, доска состояния), а в
    // оболочке субагента этой переменной нет: её задаёт команда в сессии человека, и до
    // стадии она не доезжает. Значит либо роль подставляет путь, либо ссылка не работает
    // вовсе — именно так и жила ссылка на lint-policy.md. Путь у сборщика есть, отдаём
    // его прямо в промпт; нет пути — молчим, иначе роль подставит пустую строку и получит
    // `node "/scripts/..."`.
    (PLUGIN_ROOT ? `FIRM2-ENGINE: ${PLUGIN_ROOT}\n` : '')
  )
}

// Модель Разработчика. Метка high-complexity поднимает его на Opus — это правило
// движка, а не настройка проекта, поэтому оно действует и когда секции models нет
// вовсе; проект может сменить обе модели ключами developer и developer_high_complexity.
function devModel(highComplexity) {
  if (highComplexity) return MODELS.developer_high_complexity || 'opus'
  return MODELS.developer || null
}

// В подписи агента показываем модель, только если она задана: иначе на дашборде
// Workflow не видно, на чём реально пошла сложная задача.
// Та же эскалация у Тестировщика, и по тому же доводу, по какому она есть у Разработчика:
// на метке `high-complexity` код пишут сильной моделью ИМЕННО потому, что задача сложная, —
// а тесты к этому коду писались бы слабой. Проверяющий не должен быть слабее проверяемого
// там, где сложность объявлена явно.
//
// Ревьюера эта правка НЕ трогает, и это решение, а не недоделка: на рискованной задаче ревью
// ведёт панель из трёх голосов на каждую попытку, то есть подъём модели там умножает цену
// на три. Замысел панели — независимость голосов, а не способность одного; вердикт выносится
// против явных критериев приёмки, а не вкусом. У Тестировщика же прогон один.
//
// Умолчания нет намеренно: без ключа `tester_high_complexity` в `.firm/config` ничего не
// меняется и ничего не дорожает молча. У Разработчика умолчание `opus` есть, потому что это
// правило движка с самого начала; здесь — выбор проекта. Решение 02.10.2026.
function testerModel(highComplexity) {
  if (highComplexity && MODELS.tester_high_complexity) return MODELS.tester_high_complexity
  return MODELS.tester || null
}

function devModelTag(highComplexity) {
  const m = devModel(highComplexity)
  return m ? ` [${m}]` : ''
}

// То же для Тестировщика, и не ради симметрии: эскалация, которой не видно в прогоне,
// снаружи неотличима от неработающей. Ключ в конфиге есть, `firm-state.mjs models` его
// отдаёт — а доехал ли он до сборщика, без метки в ярлыке не скажет ничто. Замечание
// тестировщика 02.10.2026, и оно про тот самый класс «работает на бумаге».
function testerModelTag(highComplexity) {
  const m = testerModel(highComplexity)
  return m ? ` [${m}]` : ''
}

