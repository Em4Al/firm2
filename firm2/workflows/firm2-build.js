// ПОСЛЕ него, — это утверждение о будущем. Замер проект-В 31.10–01.11.2026: три захода
// отклонены за расхождение объявления с диффом, и ни одно не было виной исполнителя —
// файлы дописывал Тестировщик, шедший следом по тому же дереву. Теперь объявлять нечего:
// список есть факт о ветке, и предъявляет его код.
async function taskDiffOf(task) {
  if (!PLUGIN_ROOT) return null
  const r = await tryCall(`дифф:${task.id}`, () => agent(
    `Выполни две команды и верни их результат. Первая:\n` +
      `  node "${PLUGIN_ROOT}/scripts/firm-state.mjs" task-diff --ticket ${task.id} --json\n` +
      `Ответ — JSON с полями base, files (путь, added, deleted), added, deleted, uncommitted.\n` +
      `ВТОРАЯ — сверка снятых тестов, с основанием ИЗ ПЕРВОГО ответа (поле base):\n` +
      `  node "${PLUGIN_ROOT}/scripts/test-audit.mjs" --removed --base <base> --json\n` +
      `Её ответ — JSON с полями checked, removed (file, line, test, verdict, why), added.\n` +
      `Верни { state: "ok", base, files, added, deleted, uncommitted, removed, ` +
      `removed_checked, removed_added } — списки КАК ЕСТЬ: не сокращай, не сортируй, не ` +
      `фильтруй и ничего не добавляй от себя. \`removed\` переноси целиком, вместе с полями ` +
      `verdict и why: судить снятое будет Ревьюер, а не ты.\n` +
      `Первая команда не запустилась, упала или ответила не-JSON → { state: "unknown" } и ` +
      `положи в output то, что увидел. Сорвалась ТОЛЬКО вторая → state всё равно "ok", ` +
      `removed_checked: false и причина в output: дифф снят, а сверка снятого — нет, и это ` +
      `разные знания. Своего мнения о задаче не высказывай и файлов не трогай: список ` +
      `снимает команда, ты её перо.`,
    { agentType: A.devops, ...on('devops'), schema: DIFF_SCHEMA, label: `дифф:${task.id}`, phase: 'Build' },
  ), null, task.id)
  if (!r || r.state !== 'ok' || !Array.isArray(r.files)) {
    log(`Задача ${task.id}: дифф машиной снять не удалось (${(r && r.output) || '—'}) — Ревьюер судит ветку сам`)
    return null
  }
  return r
}

// Предъявление диффа Ревьюеру. Два утверждения, и оба важны: список снят кодом, а значит
// объявление роли в протоколе доказательством НЕ является — ни в ту, ни в другую сторону.
function diffEvidence(diff) {
  if (!diff) {
    return (
      ` ДИФФ МАШИНОЙ СНЯТЬ НЕ УДАЛОСЬ — сними сам: ` +
      `\`git diff --numstat <точка ветвления>...task/<id>\`. Расхождение списка файлов, ` +
      `ОБЪЯВЛЕННОГО в протоколе, с настоящим диффом замечанием НЕ считай: после Разработчика ` +
      `по тому же дереву идёт стадия теста и дописывает свои файлы, так что объявление ` +
      `устаревает не по его вине (Д-37). Судить надо сам дифф.`
    )
  }
  const files = diff.files.map((f) => `${f.path} (+${f.added ?? '?'}/−${f.deleted ?? '?'})`)
  const dirty = Array.isArray(diff.uncommitted) ? diff.uncommitted : []
  return (
    ` ДИФФ ЗАДАЧИ СНЯТ ДВИЖКОМ, последним — после стадии теста${
      diff.base ? `, от точки ветвления ${String(diff.base).slice(0, 12)}` : ''
    }: ${diff.files.length} ${plural(diff.files.length, 'файл', 'файла', 'файлов')}, ` +
    `+${diff.added ?? '?'}/−${diff.deleted ?? '?'} строк.\n` +
    `  ${files.slice(0, 40).join('\n  ')}${diff.files.length > 40 ? '\n  …' : ''}\n` +
    `ЭТО и есть состав работы — судить надо его, а не список, объявленный в протоколе. ` +
    `Расхождение объявления с этим списком замечанием НЕ считай и в criteria_results не ` +
    `вноси: объявление пишет Разработчик, а дифф после него дополняет стадия теста, идущая ` +
    `по тому же дереву (Д-37 — три захода проект-В сорваны ровно на этом, и ни один не был ` +
    `виной исполнителя).` +
    (dirty.length
      ? `\nНЕЗАКОММИЧЕНО в дереве задачи (${dirty.length}): ${dirty.slice(0, 20).join(', ')}` +
        `${dirty.length > 20 ? ' …' : ''} — в ветке этого НЕТ, и для тебя этих файлов не ` +
        `существует. Если в них лежит работа по критериям, это основание отклонить: ` +
        `«написал и не закоммитил» — четыре бага обкатки из шести.`
      : '') +
    removalEvidence(diff)
  )
}

// Снятые тесты — Ревьюеру, сверкой движка, а не вопросом к его памяти. Право снимать тест
// роль получила 10.11.2026 (решение человека, первый из двух отложенных шагов уборки), и
// у права есть ровно одно условие — снятие не бывает молчаливым. Условие, оставленное в
// одном промпте Ревьюера, было бы просьбой; здесь оно предъявлено фактом.
function removalEvidence(diff) {
  if (!diff) return ''
  const list = Array.isArray(diff.removed) ? diff.removed.filter(Boolean) : []
  if (diff.removed_checked === false) {
    return (
      `\nСНЯТЫЕ ТЕСТЫ СВЕРИТЬ НЕ УДАЛОСЬ — это «не проверено», а не «не снято». Спроси сам: ` +
      `\`node <движок>/scripts/test-audit.mjs --removed --base <точка ветвления>\`. Пока не ` +
      `спросил — ось снятых тестов у тебя НЕ пройдена, так и скажи в notes.`
    )
  }
  if (!list.length) {
    return diff.removed_checked
      ? `\nСнятых тестов нет: сверка движка (test-audit --removed) не нашла ни одного${
        diff.removed_added ? `, добавлено ${diff.removed_added}` : ''
      }.`
      : ''
  }
  const by = (v) => list.filter((x) => String(x.verdict) === v)
  const forbidden = by('запрещено')
  const need = by('требует карточки')
  return (
    `\nСНЯТЫЕ ТЕСТЫ (${list.length}), сверка движка — снимать тест роль ВПРАВЕ, молча не вправе:\n` +
    list.slice(0, 20).map((x) => `  [${x.verdict}] ${x.file}:${x.line} — ${x.test}\n      ${x.why}`).join('\n') +
    `${list.length > 20 ? '\n  …' : ''}\n` +
    (forbidden.length
      ? `  ЗАПРЕЩЕНО снято: ${forbidden.length} — это основание ОТКЛОНИТЬ. Такой тест помечен ` +
        `человеком либо назван инвариантом, и отменять записанное решение роль права не получала.\n`
      : '') +
    (need.length
      ? `  ТРЕБУЕТ КАРТОЧКИ: ${need.length}. Машинного довода за снятие нет — суди карточку приёма ` +
        `firm-test-audit в отчёте стадии: что тест ловил, чем это ловится ещё (файл и строка), чем ` +
        `доказано. Карточки нет или в ней «ничем» — отклоняй.\n`
      : '') +
    `  И держи границу своей независимости: судишь ДОВОД, а не вкус. «Тест полезный» без ` +
    `названного случая, который останется непокрытым, — предпочтение, а не замечание.`
  )
}

// Что Тестировщик предъявил как доказательство. До 04.10.2026 его structured output
// выбрасывался (`await agent(...)` без присваивания), и Ревьюер, которому велено «проверь
// адекватность тестов», не видел ни пропусков прогона, ни мутационной проверки — хотя
// роль их делала. Это и есть вторая по частоте причина отклонений: судили вслепую.
function testEvidence(tested, task) {
  if (!tested || typeof tested !== 'object') return ''
  const rep = tested.report && typeof tested.report === 'object' ? tested.report : {}
  const mc = tested.mutation_check && typeof tested.mutation_check === 'object' ? tested.mutation_check : null
  const parts = []
  if (Number(rep.skipped) > 0) {
    parts.push(`прогон ПРОПУСТИЛ ${Number(rep.skipped)} тест(ов): ${tested.skipped_why || 'без объяснения'}`)
  }
  if (mc && mc.done && mc.evidence) parts.push(`мутационная проверка: ${mc.evidence}`)
  else if (mc && mc.why_not) parts.push(`мутационной проверки нет: ${mc.why_not}`)
  else parts.push('мутационной проверки Тестировщик не предъявил')
  // Протокол стадии — в промпт надзора. Раньше он лежал в файле задачи, и Ревьюер читал
  // его оттуда; теперь место протокола — событие, а до Ревьюера его доводит движок. Без
  // этой строки правка «не пиши в карточку» отобрала бы у надзора предмет проверки.
  const proto = tested.protocol ? String(tested.protocol).trim() : ''
  return `\nЧто предъявил Тестировщик — ${parts.join('; ')}. Это его слова, а не установленный факт: ` +
    `проверять адекватность тестов всё равно тебе, но теперь есть что проверять.\n` +
    // Пустой протокол на браузерной задаче НАЗЫВАЕТСЯ, а не опускается. До 0.4.142 здесь
    // стояло одно условие, и «не предъявлено» выглядело для надзора ровно как «раздела нет»:
    // факт у движка машиночитаемый (поле ответа пусто), а до Ревьюера доезжала тишина. Это
    // И-12 — «не знаю» не равно «соблюдено»: пустота обязана звучать отдельным ответом.
    (proto
      ? `Протокол стадии, как она его предъявила (он же лежит в её закрывающем событии):\n${proto}\n`
      : needsBrowser(task)
        ? `ПРОТОКОЛ СТАДИИ НЕ ПРЕДЪЯВЛЕН: поле \`protocol\` её ответа пусто, и в закрывающем ` +
          `событии протокола нет. Задача помечена «${BROWSER_LABEL}», то есть живой прогон ` +
          `обязателен, а непредъявленный прогон от несделанного не отличается — это замер ` +
          `движка, а не твоё впечатление. Искать протокол в файле задачи НЕ НАДО: с 0.4.140 ` +
          `его там нет и быть не должно, а найденный там — не предъявление, а тот самый ` +
          `дефект, от которого карточка перестала быть общим якорём.\n`
        : '') +
    runsEvidence(tested, task) +
    qaNarrowRule()
}

// Что сужение задачного прогона значит ДЛЯ ВЕРДИКТА. Принять задачу по узкому прогону
// можно — он судит её критерии; утверждать по нему, что поставка цела, нельзя.
function qaNarrowRule() {
  if (!TASK_TESTS_NARROWED) return ''
  return (
    `\nЗАДАЧНЫЙ ПРОГОН СУЖЕН ПРОЕКТОМ: задачи проверяются командой «${TASK_TEST_CMD}», полный ` +
    `набор («${FULL_TEST_CMD}») гоняется на воротах поставки. Принять задачу по узкому прогону ` +
    `МОЖНО: он судит её критерии, и требовать полного набора на каждой попытке — ровно та ` +
    `цена, ради которой проект и сузил. Чего делать НЕЛЬЗЯ — утверждать по нему полноту: ` +
    `фразы «набор зелёный», «регрессий нет» в вердикте без оговорки, что прогон узкий, ` +
    `непредъявимы. Критерий, который закрывается только тем, чего в задачном наборе нет, — ` +
    `это находка: скажи о ней в notes, а не принимай его молча непроверенным.\n`
  )
}

// Предъявимый прогон — то, что превращает «не принимай на слово» из «перепрогоняй всё» в
// «проверь отпечаток». Без sha это снова слова, поэтому стороны без sha не предъявляются
// вовсе: сказать «прогон был» и не сказать, на чём, — хуже, чем промолчать.
function runsEvidence(tested, task) {
  const r = tested.runs && typeof tested.runs === 'object' ? tested.runs : null
  if (!r) {
    return '\nПрогон Тестировщик НЕ предъявил (ни sha, ни команды), и это само по себе ' +
      'замечание. Что делать тебе: сторону ТОЧКИ ВЕТВЛЕНИЯ движок снял сам (см. ниже) — её ' +
      'не гоняй; свою проверку делай АДРЕСНО по критериям, которые судишь, на HEAD дерева ' +
      'задачи. Холодное дерево на точке ветвления не укладывается ни в один вызов: стадия, ' +
      'которая это сделала, стоила 155 минут вместо 20 (замер 30.10.2026).\n'
  }
  const side = (name, o) => {
    if (!o || typeof o !== 'object' || !o.sha) return `${name}: не предъявлен`
    const red = Array.isArray(o.red) ? o.red.filter(Boolean) : []
    return `${name}: sha ${String(o.sha).slice(0, 12)}` +
      (o.cmd ? `, команда \`${String(o.cmd).slice(0, 160)}\`` : ', команда не названа') +
      `, красных ${red.length || Number(o.failed) || 0}` +
      (red.length ? ` (${red.slice(0, 20).join(', ')}${red.length > 20 ? ' …' : ''})` : '')
  }
  return `\nПредъявленный прогон — ${side('точка ветвления', r.base)}; ${side('HEAD задачи', r.head)}.\n` +
    trunkEvidence(tested, task) +
    'Это ФАКТ О КОММИТЕ, а не суждение, и проверяется он отпечатком, а не повтором: сверь ' +
    'sha точки ветвления с `git merge-base` дерева задачи и sha HEAD с её вершиной — две ' +
    'дешёвые команды. Сошлось — список красных на точке ветвления бери как данность, они не ' +
    'этой задачи. Перепрогоняй АДРЕСНО то, что оспариваешь или что закрывает судимый тобой ' +
    'критерий. Полный перепрогон — твоё право и акт спора: сделал — скажи в notes, что ' +
    'именно не сошлось. Не сошлись sha, сторона не предъявлена или числа не вяжутся — ' +
    'возьми сторону точки ветвления из основания, снятого ДВИЖКОМ (оно ниже, со своим sha), ' +
    'и прогони адресно только спорное на HEAD. Заводить своё дерево на точке ветвления не ' +
    'надо ни в одном случае: за этот коммит уже заплачено один раз на всю волну.\n'
}

// Подтверждение красного поставки снимками, которые движок снял САМ.
//
// Утверждение «это красное внесла поставка» проверяемо целиком: красное обязано стоять на
// ТОЧКЕ ВЕТВЛЕНИЯ задачи и НЕ стоять на ветке-цели — ровно та разница, которой стадию и
// учили. Не стоит ни там, ни там — утверждение не подтверждено ничем: либо имя названо не
// так, либо красное живёт только на HEAD задачи, то есть принадлежит ей.
//
// Движок здесь не судит и не снимает: он СВЕРЯЕТ и называет, чем подтверждено (ADR-0009).
// Снять красное у поставки может только человек, а неподтверждённое, тихо уехавшее в итог,
// — это тот же дефект, что девять безымянных красных на демо 13.10.2026, с обратным знаком.
function redNamed(list, name) {
  const n = String(name).trim().toLowerCase()
  if (!n) return false
  return (Array.isArray(list) ? list : []).some((r) => {
    const x = String(r).trim().toLowerCase()
    return x === n || x.includes(n) || n.includes(x)
  })
}

// Обёртка, и она тут не для красоты (Д-72). Отнесение красных поставки — ДИАГНОСТИКА:
// задачу оно не блокирует и ничего не решает. Но стояло оно на несущем пути (Test → QA), и
// одной брошенной отсюда ошибки хватило, чтобы каждая задача волны потеряла вердикт после
// пройденных разработки и тестов. Цена сбоя обязана равняться потере диагностики, а не
// потере работы, поэтому несчитанное отнесение есть `state: "unknown"` с причиной.
//
// Ловить «всё» — обычно признак того, что причину не понимают. Здесь понимают: причина
// названа в сообщении и попадёт в лог и в итог, а инвариант И-12 соблюдён — это «не знаю»,
// и так оно и подписано.
function verifyDeliveryRed(names, task) {
  try {
    return attributeDeliveryRed(names, task)
  } catch (e) {
    const why = `сверка отнесения сорвалась: ${e && e.message ? e.message : 'причина не прочиталась'}`
    log(`ВНИМАНИЕ: отнесение красных поставки не посчитано (${why}). Вердикт задачи это не отменяет.`)
    // Имена читаем через `safe`: сорваться сверка могла И на самом имени (стадия вправе
    // вернуть в списке что угодно), а второй раз падать на той же причине уже в обработчике
    // — это снова потеря вердикта, только этажом выше.
    const safe = (x) => { try { return String(x) } catch { return 'имя не прочиталось' } }
    return (Array.isArray(names) ? names : []).map((name) => ({ name: safe(name), state: 'unknown', ts: RUN_TS, why }))
  }
}

function attributeDeliveryRed(names, task) {
  const id = task && task.id ? task.id : ''
  const b = BASE_BY_TASK.get(id) || null
  const t = TRUNK
  // Момент отнесения назван ВРЕМЕНЕМ, ПРИШЕДШИМ В `args` (Д-72). Довод прежний и верный
  // (Д-65): список красных успевает устареть за прогон — у проект-В четыре имени из восьми
  // зазеленели по ходу, а два названных теста к итогу перестали существовать, — поэтому
  // отнесение есть утверждение о моменте.
  //
  // Но взять время САМ прогон не может: раннер Workflow запрещает `new Date()` и `Date.now()`
  // («breaks resume») и роняет этим ВЕСЬ вызов стадии. Я поставил здесь `new Date()` в
  // 0.4.135 и сломал переход Test → QA у каждой задачи: три задачи проект-В прошли разработку
  // и тесты до конца и встали без вердикта, влито ноль, прогон сняли руками. Регрессия
  // прошла мои тесты потому, что они исполняют тело прогона обычным Node, где `Date` есть, —
  // значит проверять это должен рубеж статически (шаг 3ж), а не тест.
  const ts = RUN_TS
  return names.map((name) => {
    const onTrunk = t ? redNamed(t.red, name) : false
    // Порядок проверок: сначала ветка-цель. Предсуществующее красное опознаётся ОДНИМ
    // снимком, и отсутствие второго этому не мешает — а до 0.4.135 обе половины требовались
    // вместе, и восемь имён проект-В получили «неизвестно» при снятом основании ветки-цели.
    if (onTrunk) return { name, state: 'pre-existing', ts, trunk: t.sha, why: `стоит на «${MAIN_BRANCH}» (${t.sha.slice(0, 12)}) — предсуществующее, не поставки` }
    if (!b || !t) {
      return {
        name,
        state: 'unknown',
        ts,
        why: !t
          ? 'основание ветки-цели не снято — сверять не с чем'
          : `точка ветвления ${id} не снята: ${BASE_FAIL.get(id) || 'зонд основания не отвечал'}`,
      }
    }
    const onBase = redNamed(b.red, name)
    if (onBase) return { name, state: 'confirmed', ts, base: b.sha, why: `стоит на точке ветвления ${b.sha.slice(0, 12)} и не стоит на «${MAIN_BRANCH}»` }
    return { name, state: 'unproven', ts, base: b.sha, trunk: t.sha, why: `нет ни на точке ветвления ${b.sha.slice(0, 12)}, ни на «${MAIN_BRANCH}» ${t.sha.slice(0, 12)} — значит либо имя не то, либо красное только на HEAD задачи, то есть её` }
  })
}

// Что из основания сверки видит Ревьюер. Отдельно от `runs`, потому что это НЕ слова
// Тестировщика: сторону `trunk` снял движок, и перегонять её Ревьюеру нечего.
