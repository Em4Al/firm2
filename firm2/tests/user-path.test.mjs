// ── Разрыв, который назван человеку и решения не получил ─────────────────────
//
// Поправка 04.11.2026 по случаю проект-В: признак причины знал только «по замыслу», и на
// пути ведущего у них оказался разрыв другого рода — первый контакт с ботом происходит ВНЕ
// продукта (адреса бота в продукте нет нигде, ссылку даёт Админ лично). Разрыв законен не
// замыслом, а тем, что он назван человеку и решения пока нет. Выходов у Архитектора было
// два, и оба плохие: соврать «по замыслу» либо принять блокирующую находку, которая велит
// ему решить то, что решает человек (против ADR-0009).
test('«ждёт решения» — не дефект и не молчание: уходит вопросом на ворота', (t) => {
  const p = makeProject(t, { tasks: ['T-001'] })
  put(p, [
    '## Путь: ведущий',
    'цель: завести партию и начать её',
    table([
      '| получить ссылку на бота | Админ — ждёт решения: адреса бота в продукте нет нигде, ссылку даёт Админ лично | без правила: вне продукта | вне продукта |',
      '| завести партию | ведущий | без правила: обычный ход | T-001 |',
      '| откатить партию в «создана» | Админ — по замыслу: откат принадлежит ему (BR-24) | без правила: так решено | существует, не трогаем |',
    ]),
  ].join('\n'))
  const a = userPathAudit(p.root, p.change)
  assert.deepEqual(a.findings, [], `вопрос — не дефект: ${a.findings.join(' | ')}`)
  assert.equal(a.open_questions.length, 1, 'и не молчание: на ворота он уходит названным')
  assert.match(a.open_questions[0], /адреса бота в продукте нет/, 'в вопросе стоит причина словами автора, а не ссылка на строку')
  // Два рода законного разрыва в одной таблице различаются: задуманный молчит совсем.
  assert.equal(/откатить/.test(a.open_questions[0]), false)
})

