  put(p, ['## Путь: ведущий', 'цель: завести партию', table([
    '| завести партию | ведущий | BR-7 | T-001 |',
    '| узнать адрес бота | ведущий | BR-7 | ждёт решения человека: адреса бота в продукте нет нигде |',
  ])].join('\n') + '\n')
  const st = userPathState(p.root, p.change)
  assert.deepEqual(st.findings, [], st.findings.join(' | '))
  assert.equal(st.open_questions.length, 1, 'шаг, не сделанный ничем, не имеет права пройти молча')
  assert.match(st.open_questions[0], /адреса бота/)
