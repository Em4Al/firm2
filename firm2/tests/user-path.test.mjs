test('«по замыслу человека: …» снимает разрыв, а не требует ритуальной формы', (t) => {
  const p = makeProject(t, { tasks: ['T-001'] })
  brd(p, '# BRD\n- **BR-7.** Ведущий заводит партию.\n')
  put(p, ['## Путь: ведущий', 'цель: завести партию', table([
    '| завести партию | ведущий | BR-7 | T-001 |',
    '| открыть вход | Админ — по замыслу человека: вход открывает он лично | BR-7 | T-001 |',
  ])].join('\n') + '\n')
  const st = userPathState(p.root, p.change)
  assert.deepEqual(st.findings, [], st.findings.join(' | '))
  assert.deepEqual(st.paths[0].roles_involved, ['ведущий', 'Админ'], 'и роль из клетки взята одна, без хвоста оговорки')
})

test('причина уходит человеку без формы, в которой записана', (t) => {
  const p = makeProject(t, { tasks: ['T-001'] })
  brd(p, '# BRD\n- **BR-7.** Ведущий заводит партию.\n')
  put(p, ['## Путь: ведущий', 'цель: завести партию', table([
    '| завести партию | ведущий | BR-7 | T-001 |',
    '| узнать адрес бота | Админ — ждёт решения человека: адреса бота в продукте нет | BR-7 | T-001 |',
  ])].join('\n') + '\n')
  const st = userPathState(p.root, p.change)
  assert.equal(st.open_questions.length, 1, JSON.stringify(st.open_questions))
  assert.match(st.open_questions[0], /Человеку на воротах: адреса бота в продукте нет/)
})
