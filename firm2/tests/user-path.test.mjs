// ── Оговорка пишется прозой: между словом и двоеточием стоят слова (Д-54) ────
//
// Замер 06.11.2026 по отчёту проект-В. Признак требовал двоеточия СРАЗУ после слова
// оговорки, а естественный порядок слов — «ждёт решения ЧЕЛОВЕКА: …». Последствий два, и
