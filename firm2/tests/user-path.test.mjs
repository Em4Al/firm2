// ── Исполнитель — имя роли, а не ячейка целиком (замер 05.11.2026) ──────────
//
// Первая живая поставка под этими воротами (проект-В, G-018). Строка, которую человек читает
// на воротах, выглядела так: «игрок: шагов 26, исполнителей 4 (игрок, игрок — по замыслу:
// решение человека 05.11.2026 — мест у кнопки ровно два…, игрок — по замыслу: …, игрок —
// по замыслу: …)». Число завышено вчетверо, а причины разрывов вывалились целыми фразами
// в ту самую строку, ради краткости которой она и заведена. Один исполнитель с тремя
// оговорками — это один исполнитель.
test('оговорка в ячейке «кто исполняет» не делает второго исполнителя', (t) => {
  const p = makeProject(t, { tasks: ['T-001'] })
  brd(p, '# BRD\n- **BR-7.** Игрок выбирает рисунок.\n')
  put(p, ['## Путь: игрок', 'цель: доиграть партию', table([
    '| выбрать рисунок | игрок | BR-7 | T-001 |',
    '| открыть панель | игрок — по замыслу: мест у кнопки ровно два, вход и панель | BR-7 | T-001 |',
    '| сузить окно | игрок — ждёт решения: порог ниже границы поддержки | BR-7 | T-001 |',
  ])].join('\n') + '\n')
  const st = userPathState(p.root, p.change)
  assert.deepEqual(st.paths[0].roles_involved, ['игрок'],
    `исполнитель один: ${JSON.stringify(st.paths[0].roles_involved)}`)
  const line = userPathLines(st).find((l) => /игрок: шагов/.test(l))
  assert.equal(/исполнителей/.test(line), false, `в строке ворот лишнего нет: ${line}`)
  assert.equal(/по замыслу/.test(line), false, 'и причина разрыва не вывалилась в неё фразой')
  // Разрыв при этом никуда не делся: нерешённый уехал вопросом, названный замыслом — молчит.
  assert.equal(st.open_questions.length, 1)
})

