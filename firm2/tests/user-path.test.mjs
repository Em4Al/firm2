// Путь пользователя: восьмой вход ворот 1 (отчёт проект-В 03.11.2026, запрошено человеком).
//
// Что чинится. Поставка прошла ворота со ВСЕМИ зелёными гейтами движка и была принята
// человеком, но не работала как замысел: в пути самостоятельного ведущего второй шаг из
// четырёх принадлежал Админу, и в поставке его не было ни требованием, ни задачей, ни
// спекой. Гейты этого не видели ПО ПОСТРОЕНИЮ — все пять сверяют связность плана с тем,
// что в плане есть, а здесь не хватало того, чего нет нигде. Связность — не полнота.
//
// Поэтому проверяется здесь не «есть ли файл», а само свойство: НЕПРЕРЫВНОСТЬ пути роли и
// разрешимость каждой ссылки. Главный тест — восстановленный случай проект-В: таблица из
// четырёх шагов, в которой один чужой и ничем не сделан.
import test from 'node:test'
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { userPathFindings, userPathState, userPathAudit, parseUserPath, userPathLines } from '../scripts/lib/firm.mjs'
import { makeProject } from './helpers.mjs'

const put = (p, body) => {
  const file = join(p.tasksPath, '..', 'user-path.md')
  writeFileSync(file, body)
  return file
}

const brd = (p, text) => {
  mkdirSync(join(p.root, 'docs', 'product'), { recursive: true })
  writeFileSync(join(p.root, 'docs', 'product', 'BRD.md'), text)
}

const adr = (p, name, head) => {
  mkdirSync(join(p.root, 'docs', 'adr'), { recursive: true })
  writeFileSync(join(p.root, 'docs', 'adr', name), head)
}

const table = (rows) =>
  ['| шаг | кто исполняет | чем разрешено | чем сделано |', '|---|---|---|---|', ...rows].join('\n')

const found = (list, re) => list.filter((f) => re.test(f))

test('файла нет — это находка, а не молчание: вход обязателен', (t) => {
  const p = makeProject(t, { tasks: ['T-001'] })
  const f = userPathFindings(p.root, p.change)
  assert.equal(f.length, 1)
  assert.match(f[0], /user-path\.md/)
  assert.match(f[0], /ПЕРВЫМ/, 'порядок входов — часть находки: этот вход показывается первым')
})

test('случай проект-В целиком: чужая роль посреди пути и пустое «чем сделано»', (t) => {
  const p = makeProject(t, { tasks: ['T-303', 'T-309'] })
  put(p, [
    '# Путь пользователя — ch',
    '',
    '## Путь: ведущий',
    'цель: завести партию и довести её до начала, не обращаясь к Админу',
    '',
    table([
      '| завести партию по ссылке из бота | ведущий | без правила: обычный ход | T-303 |',
      '| открыть вход: «создана» → «сбор игроков» | Админ | без правила: так в ADR | — |',
      '| запустить партию | ведущий | без правила: обычный ход | существует, не трогаем |',
      '| отменить партию | ведущий | без правила: обычный ход | T-309 |',
    ]),
  ].join('\n'))

  const f = userPathFindings(p.root, p.change)
  const broken = found(f, /прерывается на шаге/)
  assert.equal(broken.length, 1, `разрыв обязан быть назван один раз: ${f.join(' | ')}`)
  assert.match(broken[0], /Админ/, 'в находке назван исполнитель — иначе её нечем лечить')
  const undone = found(f, /ничем не сделан/)
  assert.equal(undone.length, 1, 'поведение заявлено, задачи нет — вторая половина того же случая')
  assert.match(undone[0], /сбор игроков/, 'назван ШАГ, а не номер строки: человек читает шаги')
})

