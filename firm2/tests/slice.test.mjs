// Нарезка: сценарий, закрытый двумя задачами без границы между ними.
//
// Дефект Q поставки проект-В 3.2: выгрузка сущности файлом написана дважды независимо —
// `T-113` отвечала за способность, `T-116` реализовала её же в каркасе раздела, и обе
// ссылались на одно требование спек-дельты.
//
// Тесты держат не формат находки, а ГРАНИЦУ ШУМА, и она здесь вся суть. Отчёт по дефекту
// предлагал считать находкой само деление требования между задачами; замер показал, что
// так считать нельзя — требование делят 11 групп из 26, и почти все законно (сервер и
// экран, каркас и формы). Поэтому находка — отсутствие границы, а граница предъявима
// двумя способами: `depends_on` или имя другой задачи в тексте. Каждый из двух снимает
// находку, и каждый проверяется отдельным тестом: при обкатке первый вариант проверки
// (взаимное упоминание) давал 7 находок из 11 вместо 3.
import test from 'node:test'
import assert from 'node:assert/strict'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { criteriaFindings, requirementRefs, sliceFindings } from '../scripts/lib/firm.mjs'
import { makeProject } from './helpers.mjs'

function task(p, id, { depends_on = [], body = '' } = {}) {
  writeFileSync(
    join(p.tasksPath, `${id}.md`),
    `---\nid: ${id}\ntitle: ${id}\nstatus: todo\nparallel_safe: true\n` +
      `depends_on: [${depends_on.join(', ')}]\nlabels: []\n---\n\n## Что сделать\n\n${body}\n`,
  )
}

const find = (p) => sliceFindings(p.root, p.change)

test('ссылка на требование снимается и в единственном числе, и перечнем', () => {
  assert.deepEqual(requirementRefs('Сценарии — `specs/a/spec.md`, требование «Выгрузка файлом» (ADDED).'), ['Выгрузка файлом'])
  assert.deepEqual(
    requirementRefs('требования «Первое дело», «Второе дело» (ADDED)'),
    ['Первое дело', 'Второе дело'],
    'иначе задача с двумя требованиями в одной строке считается названной одно — ровно так дефект Q и прошёл мимо первого замера',
  )
  assert.deepEqual(requirementRefs('Текст без ссылок на требования вовсе.'), [])
})

test('требование у одной задачи — не находка, сколько бы раз оно ни называлось', (t) => {
  const p = makeProject(t, { tasks: [] })
  task(p, 'T-001', { body: 'требование «Выгрузка файлом»; ещё раз требование «Выгрузка файлом».' })
  assert.deepEqual(find(p), [])
})

test('два тикета на одно требование без границы — находка, и она называет пару', (t) => {
  const p = makeProject(t, { tasks: [] })
  task(p, 'T-001', { body: 'требование «Выгрузка файлом»' })
  task(p, 'T-002', { body: 'требование «Выгрузка файлом»' })
  const f = find(p)
  assert.equal(f.length, 1, JSON.stringify(f))
  assert.match(f[0], /Выгрузка файлом/)
  assert.match(f[0], /T-001 и T-002/)
})

test('граница объявлена depends_on — молчание', (t) => {
  const p = makeProject(t, { tasks: [] })
  task(p, 'T-001', { body: 'требование «Выгрузка файлом»' })
  task(p, 'T-002', { depends_on: ['T-001'], body: 'требование «Выгрузка файлом»' })
  assert.deepEqual(find(p), [], 'порядок назван: задача объявила другую условием')
})

test('граница названа словами в тексте — молчание, и достаточно одной стороны', (t) => {
  const p = makeProject(t, { tasks: [] })
  task(p, 'T-001', { body: 'требование «Выгрузка файлом». Органы на экранах ставит `T-002`.' })
  task(p, 'T-002', { body: 'требование «Выгрузка файлом»' })
  assert.deepEqual(find(p), [], 'сказано, где кончается своя часть — а кем сказано, движку безразлично')
})

test('три задачи на требование: находки только на неогороженных парах', (t) => {
  const p = makeProject(t, { tasks: [] })
  task(p, 'T-001', { body: 'требование «Раздел редактора». Формы ведёт `T-002`.' })
  task(p, 'T-002', { depends_on: ['T-001'], body: 'требование «Раздел редактора»' })
  task(p, 'T-003', { body: 'требование «Раздел редактора»' })
  const f = find(p)
  assert.equal(f.length, 1, JSON.stringify(f))
  assert.match(f[0], /T-001 и T-003/)
  assert.match(f[0], /T-002 и T-003/)
  assert.ok(!/T-001 и T-002/.test(f[0]), 'огороженную пару в находку тащить нельзя — это и есть шум')
})

test('имя задачи вне группы границей не является', (t) => {
  const p = makeProject(t, { tasks: [] })
  task(p, 'T-001', { body: 'требование «Выгрузка файлом». Экраны ведёт `T-009`.' })
  task(p, 'T-002', { body: 'требование «Выгрузка файлом». Экраны ведёт `T-009`.' })
  assert.equal(
    find(p).length, 1,
    'граница должна быть названа МЕЖДУ этими двумя: ссылка обеих на третью задачу ' +
    'про их собственный разрез не говорит ничего',
  )
})

test('находка нарезки доходит до гейта планирования, а не живёт в стороне', (t) => {
  const p = makeProject(t, { tasks: [] })
  task(p, 'T-001', { body: 'требование «Выгрузка файлом»' })
  task(p, 'T-002', { body: 'требование «Выгрузка файлом»' })
  assert.ok(
    criteriaFindings(p.root, p.change).some((f) => /границы между T-001 и T-002 нет/.test(f)),
    'иначе разрез утверждают не глядя, а переписывают потом кодом дважды',
  )
})
