// Номера бизнес-правил: аллокатор и сверка.
//
// Разбор стадии PM 22.10.2026: промпт сам называл риск («два груминга способны взять один
// номер»), а механизма под ним не было — ни выдачи номера, ни сверки дублей, при том что
// у задач ровно это закрыто `next-id` и `doctor duplicate_ids`.
//
// Границы, которые держат эти тесты, две, и обе про шум: упоминание правила в тексте
// определением НЕ является (иначе абзац «см. BR-7» объявил бы правило дважды), а
// отменённое правило номер НЕ освобождает (иначе ссылка из архивной задачи разрешится на
// чужое правило).
import test from 'node:test'
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { brState, nextBr, brFindings } from '../scripts/lib/firm.mjs'
import { makeProject } from './helpers.mjs'

function brd(p, name, lines) {
  mkdirSync(join(p.root, 'docs', 'product'), { recursive: true })
  writeFileSync(join(p.root, 'docs', 'product', name), lines.join('\n') + '\n')
}

function task(p, id, brs) {
  writeFileSync(
    join(p.tasksPath, `${id}.md`),
    `---\nid: ${id}\ntitle: ${id}\nstatus: todo\nparallel_safe: true\nbr_refs: [${brs.join(', ')}]\nlabels: []\n---\n\n## Что сделать\n\nx\n`,
  )
}

test('номер выдаётся от максимума: отменённое правило его не освобождает', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', ['## Бизнес-правила', '', '- **BR-1.** первое', '- **BR-2.** отменено, superseded by BR-4', '- **BR-4.** четвёртое'])
  const r = nextBr(p.root, 2)
  assert.equal(r.next, 'BR-5', 'BR-3 — дырка от отменённого, переиспользовать её нельзя')
  assert.deepEqual(r.ids, ['BR-5', 'BR-6'])
  assert.equal(r.used_count, 3)
})

test('упоминание правила в тексте определением не считается', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', ['- **BR-1.** первое', '', 'Это правило уточняет BR-1 и спорит с BR-9 из соседней области.'])
  assert.deepEqual(brState(p.root).defined, [1], 'иначе каждое «см. BR-N» объявляло бы правило')
  assert.deepEqual(brFindings(p.root), [])
})

// Шесть ложных находок на живых BRD (23.10.2026). Первая редакция регулярки требовала от
// определения только одного — чтобы номер стоял в начале строки, — а перенесённая ссылка
// ровно так и выглядит: строка `  BR-45.` в BRD проект-В это хвост фразы «Следствие для
// конца сезона — BR-45.». Строки здесь взяты из живых документов дословно.
test('перенесённая ссылка в начале строки определением не считается', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', [
    '- **BR-45.** Сезон завершается, когда сумма показателей времени',
    '  Следствие для конца сезона —',
    '  BR-45.',
    '- **BR-103.** Значения по умолчанию на экране создания партии',
    '  «в четверти» — только внутри четверти, указанной на карте засады; значение по умолчанию —',
    '  BR-103. Это не общее поле: у каждой карты владений своё',
  ])
  assert.deepEqual(brState(p.root).defined, [45, 103])
  assert.deepEqual(brFindings(p.root), [], 'пять таких строк в BRD проект-В давали пять находок «определён 2 раза» — механизм против дублей сам же был шумом')
})

test('без пробела после дефиса это не элемент списка, а значит не определение', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', ['- **BR-7.** правило', 'тире без пробела markdown списком не считает:', '-BR-9. и это тоже текст'])
  assert.deepEqual(brState(p.root).defined, [7], 'пробел после маркера требует сам markdown — иначе строка и правилом не отрисуется')
})

test('определение без точки после номера — определение: отменённое правило номер держит', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', ['- **BR-115** (отменено 2026-09-29, superseded by BR-121). Прежний текст: «Кнопка в…»'])
  assert.deepEqual(brState(p.root).defined, [115], 'строка из живого BRD проект-Б: потеряем её — номер освободится и уедет в next-id')
  assert.equal(nextBr(p.root).next, 'BR-116')
})

test('один номер в двух документах — находка, и она показывает оба места', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', ['- **BR-7.** правило области A'])
  brd(p, 'BRD-002.md', ['- **BR-7.** правило области B'])
  const f = brFindings(p.root)
  assert.equal(f.length, 1, JSON.stringify(f))
  assert.match(f[0], /BR-7/)
  assert.match(f[0], /BRD-001\.md:1/)
  assert.match(f[0], /BRD-002\.md:1/)
})

test('ссылка задачи на несуществующее правило — находка; на существующее — молчание', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', ['- **BR-1.** первое', '- **BR-2.** второе'])
  task(p, 'T-001', ['BR-2'])
  assert.deepEqual(brFindings(p.root, p.change), [])
  task(p, 'T-002', ['BR-2', 'BR-77'])
  const f = brFindings(p.root, p.change)
  assert.equal(f.length, 1, JSON.stringify(f))
  assert.match(f[0], /T-002/)
  assert.match(f[0], /BR-77/)
  assert.doesNotMatch(f[0], /BR-2\b/, 'разрешившаяся ссылка в находке не участвует')
})

test('проект без BRD находок не даёт: правил нет — и сверять нечего', (t) => {
  const p = makeProject(t, { tasks: [] })
  task(p, 'T-001', ['BR-5'])
  assert.deepEqual(brFindings(p.root, p.change), [])
  assert.equal(nextBr(p.root).next, 'BR-1')
})

test('находки номеров доезжают до гейта тем же списком, что критерии', async (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', ['- **BR-7.** A'])
  brd(p, 'BRD-002.md', ['- **BR-7.** B'])
  const { criteriaFindings } = await import('../scripts/lib/firm.mjs')
  assert.ok(criteriaFindings(p.root, p.change).some((f) => /BR-7/.test(f)), 'иначе дубль увидит только тот, кто сверит руками')
})

// ── Д-42 проекта проект-В (02.11.2026): ссылка в теле правила — не определение ──
//
// `build-args` выдал шесть находок «номер определён дважды» (BR-105, 134, 183, 201, 228 и
// BR-227 четырежды). Дублей не было: все «вторые определения» — восемь строк-ссылок внутри
// тела ОДНОГО правила, в его списке «что этим меняется в уже принятом». Строки ниже взяты
// из живого документа дословно (до обхода, который проект принял коммитом 67eb2344).
test('вложенный пункт со ссылкой на правило определением не считается', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', [
    '- **BR-105.** Орган фиксации стоит в пульте',
    '- **BR-134.** Потолок ширины страницы',
    '- **BR-237.** Экран партии получает карту владений',
    '  Что этим меняется в уже принятом:',
    '  - **BR-227 п. 2 («остаток ширины принадлежит пульту») — ОТМЕНЁН в части «весь остаток».**',
    '  - **BR-134 — не трогается:** потолка страницы правило не возвращает',
    '  - **BR-105 — не трогается:** орган фиксации стоит в пульте',
  ])
  const st = brState(p.root)
  assert.deepEqual(st.defined, [105, 134, 237], 'определения только у пунктов верхнего уровня')
  assert.deepEqual(st.where.get(134), ['docs/product/BRD-001.md:2'], 'ссылка не добавляет второго места')
  assert.deepEqual(brFindings(p.root), [],
    'находка гейта требует времени человека: ложная стоила отдельного захода на перенумерацию')
})

test('знак после номера обязателен, но закрывающие звёздочки его заменяют', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', [
    '- **BR-1.** точка — форма шаблона',
    '- BR-2: двоеточие без звёздочек',
    '- **BR-3** (отменено 2026-09-29, superseded by BR-7)',
    '- **BR-9 — не трогается:** это ссылка в теле другого правила, а не определение',
  ])
  const st = brState(p.root)
  assert.deepEqual(st.defined, [1, 2, 3],
    'BR-3 — настоящее определение отменённого правила: потеряем его, и номер уедет в next-id')
  assert.equal(st.ambiguous.length, 1, 'BR-9 не выброшен молча, а назван спорной строкой')
})

// Ошибка в сторону «определение принято за ссылку» дороже обратной: номер остаётся
// свободным, и `next-id` выдаёт его второму правилу — то есть ровно тот вред, против
// которого стоит вся сверка. Поэтому такая строка не выбрасывается молча.
test('строка верхнего уровня не той формы называется находкой, а не выбрасывается', (t) => {
  const p = makeProject(t, { tasks: [] })
  brd(p, 'BRD-001.md', ['- **BR-1.** первое', '- **BR-5 потолок ширины** без знака после номера'])
  const f = brFindings(p.root)
  assert.equal(f.length, 1)
  assert.match(f[0], /BRD-001\.md:2/, 'назван адрес строки')
  assert.match(f[0], /похожа на определение/)
  assert.match(f[0], /next-id/, 'сказана цена: номер считается свободным')
})

// ── Отмена правила: три формы живых сводов и две ловушки ─────────────────────
//
// Признак отмены заведён 03.11.2026 вместе с путём пользователя (отчёт проект-В): ссылка
// шага на отменённое правило и ссылка на несуществующее лечатся по-разному, и сказать это
// надо дословно. Проверяется по живым данным: первая редакция признака читала только
// строку определения и на 214 правилах проект-В нашла НОЛЬ отменённых при трёх фактических.
test('отмена, записанная строкой ПОСЛЕ определения, читается как отмена', (t) => {
  const p = makeProject(t, { tasks: ['T-001'] })
  brd(p, 'BRD-001.md', [
    '# BRD',
    '- **BR-23.** **Ведущий может закрыть вход в партию до старта.**',
    '  **Отменено 03.11.2026** решением человека на планировании поставки, дословно:',
    '  «убери команду у ведущего». На месте правила — **BR-20**.',
    '',
    '- **BR-26.** Ведущий запускает партию.',
  ])
  const st = brState(p.root)
  assert.equal(st.retired.has(23), true, 'ровно так отмена записана в живом своде проект-В')
  assert.equal(st.retired.has(26), false, 'соседнее правило отменой не заражается: блок кончается определением')
  assert.deepEqual(st.defined, [23, 26], 'номер отменённого остаётся занятым — переиспользовать его нельзя')
})

test('строка переноса, начатая словом «отменён», отменой НЕ считается', (t) => {
  // Три случая из живого свода проект-В, на которых широкая редакция признака дала ложь:
  // BR-28 («отменён человеком 04.10.2026: экран показывает…» — это про ДРУГОЕ правило),
  // BR-134 («отменённое правило отдавало запас…»), BR-179 («**отменена**)»).
  const p = makeProject(t, { tasks: ['T-001'] })
  brd(p, 'BRD-001.md', [
    '# BRD',
    '- **BR-28.** Карта задания несёт список вариантов. Прежний порядок выбора пары',
    '  отменён человеком 04.10.2026: экран показывает плоский список допустимых пар.',
    '- **BR-134.** Потолок ширины экрана партии. В отличие от BR-127,',
    '  отменённое правило отдавало запас первой колонке, здесь он достаётся средней.',
    '- **BR-179.** Раскладка экрана партии открыта (прежняя раскладка',
    '  **отменена**). Под знаками в шапке прячутся карты целей.',
  ])
  const st = brState(p.root)
  assert.equal(st.retired.size, 0,
    'заглавная буква — признак: отмена начинает фразу, а строка переноса начинается со строчной')
})

test('отмена в одной строке с определением — обе формы живых сводов', (t) => {
  const p = makeProject(t, { tasks: ['T-001'] })
  brd(p, 'BRD-001.md', [
    '# BRD',
    '- **BR-115** (отменено 2026-09-29, superseded by BR-121). Прежний текст: «Кнопка…»',
    '- ~~**BR-3.**~~ Старое правило — superseded by BR-12, 2026-09-21.',
    '- **BR-121.** Кнопка в личном кабинете не ведёт в тупик. Заменяет BR-115.',
  ])
  const st = brState(p.root)
  assert.equal(st.retired.has(115), true, 'форма BRD проект-Б')
  assert.equal(st.retired.has(3), true, 'форма шаблона движка')
  assert.equal(st.retired.has(121), false, '«Заменяет BR-115» в тексте живого правила его не отменяет')
})
