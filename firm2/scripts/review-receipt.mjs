#!/usr/bin/env node
// Слияние задачи, чья расписка о ревью протухла, — отказ, а не абзац в промпте (ADR-0013).
//
// Что закрывается. Вердикт ревью удостоверял ТИКЕТ, а не содержимое: между `accepted` и
// слиянием ветка задачи уезжает законными способами — следующая попытка, правка руками в
// рабочем дереве, доработка «на одну строку» после вердикта, `commit --amend`. ADR-0005
// проверяет, что влили именно эту ВЕТКУ; что в ней лежало то же, что судил надзор, не
// проверял никто. Цена — непросмотренный код в поставке, числящийся принятым, и
// следующий прогон исключит задачу как закрытую.
//
// Почему гвард, а не правило в промпте стадии слияния. Тот промпт и так самый длинный в
// движке (десяток абзацев разборов отказов git), и правило в нём держалось бы на внимании
// модели. `PreToolUse` не обходится — тот же довод, что у `bash-guard.mjs` и
// `secret-scan.mjs`.
//
// Почему признак не `cwd`. `bash-guard.mjs` отличает стадию от человека по рабочему
// каталогу: деревья задач лежат вне репозитория. Здесь это не работает по устройству —
// слияние идёт в ГЛАВНОМ дереве, и вызов стадии от вызова человека не отличим. Поэтому
// отказ несёт именованный выход: `FIRM2_STALE_REVIEW=i-know` в той же команде пропускает
// слияние, записав событие. Выход есть, он виден в журнале и его нельзя сделать молча —
// это и был единственный настоящий риск (ADR-0009 против ADR-0013).
//
// И ровно здесь до 0.4.126 была подделка подписи. Событие писалось словами «пропущено
// ЧЕЛОВЕКОМ», хотя переменную берёт кто угодно — а взять её проще всего стадии, которой
// отказ мешает. Замер проект-В 04.11.2026: дважды за одну поставку журнал — объявленный
// источник истины — получил запись о согласии, которого человек не давал, и отличить
// настоящее согласие от самоназначенного по журналу было НЕЛЬЗЯ.
//
// Что исправлено, и что исправить нечем. Запись больше не называет человека: выход
// пропускает слияние «вызывающей стороной», и это всё, что движок знает. Отличить человека
// от стадии он не может по устройству (одно дерево, один канал), поэтому первым в рецепте
// отказа стоит путь, который подпись НЕСЁТ: `record --actor human` своими словами. Он
// дороже на одну команду и честнее на целое удостоверение. Побочное подтверждение из того
// же случая: классификатор рантайма дважды отклонил вызов с этим префиксом как попытку
// снятия защиты — подозрение было законным.

import { readFileSync } from 'node:fs'
import {
  repoRoot, readConfig, writeEvent, listEvents, taskTree, acceptedReceipt, isBoundTicket,
  gitSubcommands, stripHeredoc, staleReviewSplit,
} from './lib/firm.mjs'

function readStdin() {
  try {
    return JSON.parse(readFileSync(0, 'utf8'))
  } catch {
    return null
  }
}

// Слияние ветки задачи опознаётся РАЗБОРОМ ПОДКОМАНДЫ (`gitSubcommands` в lib), а не
// подстрокой. Прежний образец `\bgit\b…\bmerge\b…task/(T-…)` ловил `merge-base` — слово
// `merge` в нём кончается на границе, — то есть отклонял ЧИТАЮЩУЮ команду, которой как раз
// и смотрят, что изменилось после вердикта: отказ запрещал диагностику, к которой сам же и
// подталкивал. Поведение вдобавок было непредсказуемым: `--merged` проходил (там после
// `merge` буква), `merge-base` нет. А попав на heredoc, отказ начинал мешать записи файла,
// в ТЕКСТЕ которого встретились нужные слова. Д-22 проект-В 29.10.2026 — тот же дефект, что
// Д-20 в стороже отправки, поэтому разбор теперь один на оба (см. lib/firm.mjs).
//
// Что слиянием НЕ является: `merge-base`, `merge-tree`, `merge-file` (читают),
// `log --merges`, `branch --merged` (ключи, а не подкоманды).
function mergedTicket(cmd) {
  if (!gitSubcommands(cmd).some((g) => g.sub === 'merge')) return null
  // Тикет ищем в той же команде, но ТОЛЬКО в её части до heredoc: ветка, названная внутри
  // передаваемого текста, к слиянию отношения не имеет.
  const m = stripHeredoc(cmd).match(/\btask\/(T-[\w.]+)/)
  return m ? m[1] : null
}
// Выход для человека. Проверяем ДО разбора слияния: смысл выхода в том, что он работает
// даже когда всё остальное отказывает.
const WAIVER = /FIRM2_STALE_REVIEW\s*=\s*i-know\b/

function main() {
  const h = readStdin()
  if (!h) process.exit(0) // нет нагрузки — не наше дело, молчим

  const cmd = String((h.tool_input || {}).command || '')
  const ticket = mergedTicket(cmd)
  if (!ticket) process.exit(0)
  if (!isBoundTicket(ticket)) process.exit(0)

  const root = process.env.CLAUDE_PROJECT_DIR || repoRoot()
  if (!root) process.exit(0)
  const cfg = readConfig(root)
  if (!cfg || cfg.engine !== 'firm2') process.exit(0)

  const short = cmd.replace(/\s+/g, ' ').slice(0, 300)
  const current = taskTree(root, ticket)
  const receipt = acceptedReceipt(listEvents(root), ticket)

  // Расписки нет вовсе: задачу сливают непринятой. Это ДРУГОЙ дефект, и ответить на него
  // этим гвардом значило бы спрятать два вопроса за одним ответом (ADR-0013). Называем и
  // пропускаем: пока отказ не про то, что написано на его табличке, его обходят, а не
  // исполняют.
  if (!receipt) {
    process.stderr.write(
      `[firm2] ${ticket} сливается, а события принятия в журнале нет — ни ревью, ни ` +
        'адъюдикации, ни короткой полосы. Движок слияние не держит (это не его правило), но ' +
        'сказать обязан: проверь, то ли вливается.\n',
    )
    process.exit(0)
  }

  // Расписка старше этой версии: поля `tree` в ней нет. Отсутствие отпечатка — известное
  // состояние, а не неопределённость (И-12): называем и пропускаем. Иначе на четырёх живых
  // проектах каждая задача в работе стала бы незаливаемой подъёмом версии движка.
  if (!receipt.tree || !current) {
    process.stderr.write(
      `[firm2] ${ticket}: сверить содержимое не с чем — ` +
        (receipt.tree
          ? `ветка task/${ticket} не читается из главного дерева`
          : `расписка ${receipt.stage}/${receipt.event} записана движком без отпечатка дерева (старше 0.4.83)`) +
        '. Слияние идёт как раньше.\n',
    )
    process.exit(0)
  }

  if (receipt.tree === current) process.exit(0) // расписка свежая — молчим, это норма

  const allowed = String((cfg.guard && cfg.guard.stale_review) || 'block') === 'allow'
  const waived = WAIVER.test(cmd)

  if (allowed || waived) {
    writeEvent(root, {
      ticket,
      stage: 'guard',
      event: 'review-stale',
      actor: 'review-receipt',
      tree: current,
      notes:
        (waived
          ? 'пропущено ВЫЗЫВАЮЩЕЙ СТОРОНОЙ (FIRM2_STALE_REVIEW=i-know): подпись человека этим '
            + 'НЕ подтверждается — переменную берёт кто угодно, и движок не отличает человека '
            + 'от стадии. Согласие человека записывается событием record --actor human'
          : 'guard.stale_review: allow') +
        `: принято дерево ${receipt.tree} (${receipt.stage}/${receipt.event}), влито ${current}`,
    })
    process.stderr.write(
      `[firm2] ${ticket}: расписка о ревью протухла (принято ${receipt.tree}, в ветке ${current}), ` +
        `но слияние пропущено — ${waived ? 'выходом FIRM2_STALE_REVIEW=i-know (подписью человека это НЕ является)' : 'ключом guard.stale_review: allow'}. ` +
        'Записано событием guard/review-stale.\n',
    )
    process.exit(0)
  }

  // Расхождение, разделённое машиной: своё против подтянутого (Д-64). Печатается ДВУМЯ
  // числами, и первый список поимённо — иначе отказ верен, а его диагноз шире правды, и
  // человек начинает разбор не с того файла.
  const split = staleReviewSplit(root, ticket, receipt.tree, receipt.change)
  const NAMES = 20
  const splitLines = !split
    ? '(разделить своё и подтянутое не удалось — дифф не прочитан)\n'
    : split.why
      ? `Своё и подтянутое РАЗДЕЛИТЬ НЕ УДАЛОСЬ: ${split.why}.\n` +
        `Изменилось после вердикта файлов: ${split.files.length} — список целиком, не разделён.\n`
      : `Своих правок: ${split.own.length} файл(ов)` +
        (split.own.length
          ? ` — ${split.own.slice(0, NAMES).join(', ')}` +
            (split.own.length > NAMES ? ` и ещё ${split.own.length - NAMES}` : '')
          : '') + '\n' +
        `Подтянуто с ветки поставки feature/${split.change}: ${split.pulled.length} файл(ов) — ` +
        'чужая отсуженная работа и журнал событий; надзор её уже видел, и судить её тебе не надо.\n' +
        'СУДИТЬ НАДО ПЕРВЫЙ СПИСОК. Замер проект-В 09.11.2026: расхождение назвало 249 файлов и\n' +
        '+10 839 строк, а своей рукой в задаче было написано двадцать строк в одном файле —\n' +
        'общее число пугает и уводит разбор не туда.\n'

  process.stderr.write(
    `[firm2] ЭТА КОМАНДА СЛИЯНИЯ ${ticket} отменена: расписка о ревью протухла.\n` +
      `Команда: ${short}\n` +
      'Отменён именно вызов слияния — ни одна читающая команда этим сторожем не держится:\n' +
      '`merge-base`, `merge-tree`, `diff`, `log --merges` проходят. Смотреть расхождение\n' +
      'можно и нужно, в том числе командами ниже.\n' +
      `Принято было дерево: ${receipt.tree} — ${receipt.stage}/${receipt.event}, ${receipt.ts || 'без времени'}` +
      (receipt.file ? ` (${receipt.file})` : '') + '\n' +
      `Сейчас в ветке task/${ticket}: ${current}\n` +      splitLines +
      'Это значит, что после вердикта содержимое ветки изменилось. В поставку поехал бы код,\n' +
      'которого надзор не видел, — и числился бы принятым: следующий прогон исключит задачу\n' +
      'как закрытую, и непросмотренное станет невидимым навсегда.\n' +
      'Отпечаток берётся у ДЕРЕВА, а не у коммита: rebase и amend без правок содержимого\n' +
      'расписку не протухают. Разошлось — значит изменилось именно содержимое.\n' +
      'Что делать — по порядку, и порядок здесь не случайный:\n' +
      '  • СНАЧАЛА посмотри на команду выше: СЛИЯНИЯ В НЕЙ НЕТ? Тогда это не твой случай —\n' +
      '    нужные слова пришли ДАННЫМИ (текст разбора, тело файла, цитата шага исполнителю).\n' +
      '    Значения текстовых ключей (--notes, --message, -m и родня) и тело heredoc\n' +
      '    сторож снимает перед разбором с 10.11.2026 (Д-74), но остаток возможен: передай\n' +
      '    текст heredoc\'ом либо перефразируй цитату. Освежать расписку и подставлять\n' +
      '    FIRM2_STALE_REVIEW здесь НЕ НАДО — второе записало бы ЛОЖНОЕ guard/review-stale\n' +
      '    о пропущенной защите, которой никто не обходил;\n' +
      '  • ТОЛЬКО ЧЕЛОВЕК, РОЛИ ЭТОТ ХОД НЕДОСТУПЕН: содержимое проверил человек и берёт\n' +
      '    на себя — он записывает решение событием,\n' +
      '    своими словами, и это единственный путь, который несёт его подпись:\n' +
      `      firm-event.mjs record --ticket ${ticket} --stage review --event accepted --actor human \\\n` +
      '        --notes "влитое содержимое проверено после вердикта: <что именно изменилось>"\n' +
      '    после этого расписка свежая, и слияние проходит ОБЫЧНОЙ командой;\n' +
      '  • правка после вердикта сделана по делу — задача идёт на ревью ещё раз, обычным\n' +
      '    циклом. Это не лишний заход: судить надо то, что вливают. Если своих правок ноль,\n' +
      '    а всё расхождение подтянуто с ветки поставки, скажи это в notes прямо: судить\n' +
      '    заново надо содержимое задачи, а не подтянутое основание;\n' +
      '  • правка не нужна — верни ветку к принятому состоянию и слей его:\n' +
      `      git -C <корень> diff ${receipt.tree} task/${ticket}   # что именно добавилось после вердикта\n` +
      '  • последний выход, если не подходит ничего выше: тем же вызовом, с префиксом\n' +
      `      FIRM2_STALE_REVIEW=i-know git -C <корень> merge --no-ff task/${ticket}\n` +
      '    слияние пройдёт и запишется событием guard/review-stale. ЗНАЙ, ЧТО ОН ЗАПИСЫВАЕТ:\n' +
      '    «пропущено вызывающей стороной» — согласием человека это НЕ является и за него\n' +
      '    не сойдёт. Если решение принял человек, выход выше честнее и стоит одной команды.\n' +
      'Упомяни этот отказ в notes: он объясняет, почему слияние не сделано.\n',
  )
  process.exit(2)
}

main()
