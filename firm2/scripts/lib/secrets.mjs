import { resolve } from 'node:path'
// Поиск секретов в диффе, который вот-вот уедет в коммит.
//
// Зачем, если `.env` под песочницей нечитаем. Песочница закрывает ЧТЕНИЕ файла с
// секретами — и это работает. Она не закрывает другой путь, которым ключ попадает в
// историю: роль вписывает его в код руками или вставляет из вывода команды, которую сама
// же и запустила. Такой ключ в репозитории не отзывается удалением строки — он остаётся в
// истории, и отзывать приходится сам ключ.
//
// Приём взят из `hooks/README.md` плагина ECC (PreToolUse → pre-commit quality check,
// `github.com/affaan-m/ECC`, MIT): проверка staged-файлов перед коммитом с отказом по
// exit 2. Образцы и границы — свои.
//
// Два правила, на которых держится полезность этого файла:
//
//   1. Смотрим ТОЛЬКО на добавленные строки диффа. Секрет, который уже лежит в истории,
//      этой проверкой не чинится (его чинит отзыв ключа), а находка на нём означала бы
//      красный коммит у каждого, кто тронул файл рядом.
//   2. Образец либо узнаёт секрет по форме, либо не ставится вовсе. Проверка, которая
//      срабатывает на слове `password` в комментарии, обходится не разбором, а привычкой:
//      шум убивает сигнал надёжнее молчания (тот же довод, что у единицы измерения в
//      `DECIMAL`).

// Секреты, узнаваемые по форме. Префикс выдаёт выпустившего, длина — что это ключ, а не
// слово. На таких образцах ложных находок почти не бывает: строка `AKIA` плюс 16 знаков в
// верхнем регистре в прозе не встречается.
const SHAPED = [
  { rule: 'закрытый ключ', re: /-----BEGIN[A-Z ]*PRIVATE KEY-----/ },
  { rule: 'ключ доступа AWS', re: /\bAKIA[0-9A-Z]{16}\b/ },
  { rule: 'токен GitHub', re: /\bgh[pousr]_[A-Za-z0-9]{36,}\b/ },
  { rule: 'токен Slack', re: /\bxox[abprs]-[A-Za-z0-9-]{10,}\b/ },
  { rule: 'ключ Google API', re: /\bAIza[0-9A-Za-z_-]{35}\b/ },
  { rule: 'ключ Anthropic', re: /\bsk-ant-[A-Za-z0-9_-]{20,}\b/ },
  { rule: 'ключ Stripe', re: /\b[sr]k_(?:live|test)_[A-Za-z0-9]{16,}\b/ },
  { rule: 'ключ OpenAI', re: /\bsk-(?:proj-)?[A-Za-z0-9]{32,}\b/ },
  { rule: 'токен бота Telegram', re: /\b\d{8,10}:[A-Za-z0-9_-]{35}\b/ },
  { rule: 'JWT', re: /\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}/ },
  // Пароль внутри строки подключения. Именно здесь он чаще всего и уезжает: строку
  // копируют из вывода `docker compose` или из панели хостинга целиком.
  {
    rule: 'пароль в строке подключения',
    re: /\b(?:postgres(?:ql)?|mysql|mariadb|mongodb(?:\+srv)?|redis|amqp|ftp|smtp):\/\/[^\s:/@]+:[^\s@'"`]{3,}@/,
  },
]

// Присваивание ключу с говорящим именем. Образец мягче предыдущих, поэтому обвешан
// условиями: значение должно быть литералом в кавычках, не похожим на подстановку, и
// достаточно длинным, чтобы не быть словом.
//
// Имя собирается из частей, а не перечисляется списком: `api_key`, `apiKey`, `API-KEY` и
// `clientSecret` — одно и то же имя в четырёх стилях, и список из них неизбежно отстаёт
// от первого же проекта на другом языке. Необязательная группа типа после двоеточия нужна
// для TypeScript: `const clientSecret: string = "…"`.
const ASSIGN =
  /\b(?:api|access|refresh|auth|client|private|secret|bearer|db|database|admin|root)?[_-]?(?:key|token|secret|password|passwd|pwd|credential)\b\s*(?::\s*\w+\s*)?\s*(?:[:=]|=>|:=)\s*(['"`])([^'"`\n]{8,})\1/i

// Значение, которое ключом не является: подстановка шаблонизатора, чтение окружения,
// заглушка, замазанное значение. Список — не вкусовщина, а цена: каждая такая находка
// стоит красного коммита на ровном месте.
const PLACEHOLDER =
  /^(?:\{\{|\$\{|\$\(|<|%|\.\.\.|x{3,}|\*{3,}|\.{3,}|changeme|change_me|placeholder|example|dummy|sample|fake|test|testing|your|yours|my|some|none|null|nil|empty|undefined|redacted|secret|password|hunter2|todo|tbd|xxx)/i

const FROM_ENV = /os\.(?:getenv|environ)|process\.env|getenv\(|ENV\[|env\(|environ\[|Deno\.env|config\(|settings\./i

// Строка, помеченная человеком как заведомо не секрет. Причина обязательна: защита,
// снятая без записанной причины, хуже отсутствующей (`templates/standards/common.md` §5,
// тот же довод, что у `guard.sandbox_off`).
const WAIVER = /firm2:\s*не секрет\s*[—-]\s*\S/i

function looksLikeSecretValue(value) {
  if (PLACEHOLDER.test(value)) return false
  if (FROM_ENV.test(value)) return false
  // Пробел внутри значения — это фраза, а не ключ. Замер проект-В 04.11.2026: в заметке
  // Ревьюера стояло «?token=` в WebSocket-пути `», markdown-кавычки прочлись как границы
  // литерала, и «секретом» объявилась русская фраза «в WebSocket-пути». Присваивания там
  // не было вовсе — `?token=` это имя параметра запроса без значения. Отмены стоили двух
  // коммитов задаче, предмет которой — удостоверения в журнале: Ревьюер ОБЯЗАН был
  // написать это слово, чтобы назвать остаточное наблюдение.
  //
  // Признак сужен значением, а не видом кавычки, и это осознанно: обратная кавычка в JS
  // означает настоящий литерал (`const key = \`abc…\``), и запрещать её значило бы снять
  // проверку с живого языка ради markdown. Ключ с пробелом не бывает.
  if (/\s/.test(value)) return false
  // Одинаковые знаки по всей длине (`********`, `aaaaaaaa`) — замазка, а не ключ.
  if (/^(.)\1+$/.test(value)) return false
  // Длинное значение считаем ключом; короткое — только если в нём есть цифра. Слово
  // `correcthorse` в фикстуре ключом не является, `Pa55w0rd!` — является.
  return value.length >= 16 || /\d/.test(value)
}

/**
 * Находки в тексте унифицированного диффа (`git diff --cached`).
 *
 * Возвращает массив `{ file, rule, line, excerpt, waived }`. `waived: true` — строка
 * помечена оговоркой `firm2: не секрет — <причина>`: такая находка не блокирует, но из
 * результата не исчезает, чтобы оговорку было видно и в событии, и в ревью.
 */
// Журнал движка под сверку не попадает, и это не послабление, а граница ответственности.
// Текст события пишет ДВИЖОК для человека, а не рука для кода: удостоверения в нём нет по
// построению (ADR-0006 — журнал только дописывается, и править его нельзя даже ради
// проверки). Замер проект-В 04.11.2026: все три находки коммита лежали в `.firm/events/`, и
// две из трёх — в событиях ОТМЕНЫ, которые цитировали первую находку. То есть сверка
// кормила себя своим же протоколом, и поверхность росла на файл за попытку. Пока у журнала
// нет исключения, любая задача про секреты блокирует собственное слияние.
const JOURNAL = /(?:^|\/)\.firm\/events\//

export function findSecretsInDiff(diff) {
  const out = []
  let file = '?'
  let lineNo = 0
  for (const raw of String(diff || '').split('\n')) {
    // Имя файла берём из `+++ b/<путь>`: заголовок `diff --git` цитирует путь дважды и
    // ломается на пробелах в имени.
    if (raw.startsWith('+++ ')) {
      const m = /^\+\+\+ (?:b\/)?(.*)$/.exec(raw)
      file = m ? m[1].trim() : '?'
      continue
    }
    // Номер строки — из шапки куска. Нужен событию: называть файл и строку числом дешевле
    // и честнее, чем цитировать найденный фрагмент (см. JOURNAL выше).
    const hunk = /^@@ -\d+(?:,\d+)? \+(\d+)/.exec(raw)
    if (hunk) {
      lineNo = Number(hunk[1]) - 1
      continue
    }
    if (!raw.startsWith('+') || raw.startsWith('+++')) continue
    lineNo += 1
    if (JOURNAL.test(file)) continue
    const line = raw.slice(1)
    const waived = WAIVER.test(line)
    for (const s of SHAPED) {
      if (!s.re.test(line)) continue
      out.push({ file, line_no: lineNo, rule: s.rule, line: redact(line), excerpt: redact(s.re.exec(line)[0]), waived })
    }
    const a = ASSIGN.exec(line)
    if (a && looksLikeSecretValue(a[2])) {
      out.push({ file, line_no: lineNo, rule: 'значение присвоено ключу с говорящим именем', line: redact(line), excerpt: redact(a[0]), waived })
    }
  }
  return out
}

/**
 * Сам секрет из отказа не вытаскиваем: stderr хука уезжает в транскрипт стадии, в лог
 * прогона и в отчёт роли — то есть находка, напечатанная целиком, размножила бы ключ по
 * трём новым местам вместо одного. Оставляем начало, чтобы строку можно было найти.
 */
export function redact(text) {
  return String(text)
    .trim()
    .slice(0, 160)
    .replace(/([A-Za-z0-9_\-+/=.:]{12})[A-Za-z0-9_\-+/=.:]{6,}/g, (m, head) => `${head}…[срезано]`)
}


// Каталог, в котором на самом деле делается коммит. Называет его сама команда — двумя
// способами, и оба встречаются в прогонах:
//
//   git -C ../проект.worktrees/T-118 commit -m "…"
//   cd ../проект.worktrees/T-118 && git commit -m "…"
//
// `-C` у git накопительный, поэтому флаги применяются по порядку. Не назвал никто —
// остаётся каталог вызова: это прежнее поведение и верный ответ для коммита на месте.
export function targetDir(cmd, cwd) {
  const text = String(cmd)
  const unquote = (v) => v.replace(/^["']|["']$/g, '')
  let dir = cwd
  const cd = text.match(/^\s*cd\s+("[^"]+"|'[^']+'|[^\s;&|]+)\s*(?:&&|;)/)
  if (cd) dir = resolve(dir, unquote(cd[1]))

  // Флаги `-C` берём у ОДНОГО вызова git — того, который коммитит. Собирать их по всей
  // строке нельзя: `git -C dir add -A && git -C dir commit` дал бы `dir/dir`, то есть
  // каталог, которого нет, и проверка молча ушла бы смотреть пустой дифф. Внутри одного
  // вызова флагов может быть несколько, и git применяет их по порядку — так и делаем.
  const parts = text.split(/&&|\|\||;|\|/)
  const seg = parts.filter((x) => /\bgit\b/.test(x) && /\bcommit\b/.test(x)).pop()
    || parts.filter((x) => /\bgit\b/.test(x)).pop()
    || ''
  for (const f of seg.matchAll(/(?:^|\s)-C\s+("[^"]+"|'[^']+'|[^\s]+)/g)) {
    dir = resolve(dir, unquote(f[1]))
  }
  return dir
}
