#!/usr/bin/env node
// Защита от теста, который проверяет МОМЕНТ, а не поведение (ретро 09.10.2026).
//
// Что случилось — пять раз. BUG-043, 045, 046, 047 на проект-В и независимо BUG-018 на
// проект-Б, затем BUG-049 (T-064). Один корень: тест судит о состоянии репозитория
// по снимку, который к моменту предъявления устарел. «Страж границ» T-039f с жёстко
// вписанным `ALLOWED_FILES` после слияния краснел на диффе ЛЮБОЙ следующей задачи и
// блокировал приёмку всей очереди.
//
// Почему именно хук, а не ещё один абзац в промпте. Семейство чинили четырьмя правками
// промптов (0.4.56, 0.4.59) и пятой — переформулировкой (0.4.60). Шестая формулировка
// ничего бы не изменила: правило словесное, а ошибка делается не по злому умыслу, а по
// невнимательности — ровно как относительный путь в `write-guard.mjs`. Зато у семейства
// есть машинная подпись, выписанная в 0.4.60 самим проектом, и подпись эта grep-абельна.
//
// Правило, которое и есть граница (0.4.60): вечно живёт проверка СОСТОЯНИЯ ДЕРЕВА — та,
// что даёт тот же ответ, сколько бы задач ни легло сверху. Не «про код или про тесты», а
// «зависит ли ответ от лежащего поверх». После слияния точка ветвления съезжает на коммит
// слияния, и диф «база..HEAD» начинает показывать работу СЛЕДУЮЩЕЙ задачи.
//
// Что НЕ запрещено. `merge-base` — законный приём СТАДИИ (база прогона) и запрещённый приём
// ВЕЧНОГО теста. Поэтому проверяются только файлы, похожие на тесты, а строку со стадийной
// проверкой можно пометить явно:
//
//   # firm2: стадийная проверка — живёт один прогон, после слияния снимается
//
// Пометка обязана называть причину: молча снятая защита хуже отсутствующей.
//
// Аварийный выход — в `.firm/config`:
//   guard:
//     test_criteria: off
//
// Код возврата 2 отменяет сам вызов Write/Edit: стадия узнаёт об ошибке до того, как её
// совершила. PostToolUse здесь не годится — тест уже лёг бы в дерево.
import { readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname } from 'node:path'
import { repoRoot, readConfig, writeEvent, ticketFromBranch } from './lib/firm.mjs'

// Подпись семейства. Каждая запись — признак из разбора 0.4.60 плюс объяснение, которое
// печатается роли: отказ без причины провоцирует обход, а не исправление.
const SIGNS = [
  {
    re: /merge[-_]base/i,
    why: 'сравнение с точкой ветвления: после слияния она съезжает на коммит слияния',
  },
  {
    re: /\.\.\.\s*HEAD|HEAD\s*\.\.\./,
    why: 'трёхточечный диф с верхушкой ветки: показывает работу следующей задачи',
  },
  {
    re: /\b(?:ALLOWED|TOUCHED)_FILES\b/,
    why: 'жёсткий перечень файлов: краснеет на диффе любой следующей задачи',
  },
  {
    re: /--is-ancestor/,
    why: 'проверка «влито» своими руками: это делается в одном месте (ADR-0005)',
  },
  {
    re: /log\s+--merges/,
    why: 'проверка «влито» своими руками: это делается в одном месте (ADR-0005)',
  },
  {
    re: /git\b[^\n]*\b[0-9a-f]{7,40}\b/,
    why: 'диф от прибитого коммита-предка: предок перестаёт быть предком после слияния',
  },
]

// Пометка стадийной проверки. ПРИЧИНА ОБЯЗАТЕЛЬНА, и до 0.4.90 это было написано в
// заголовке этого же файла, в подсказке роли и в промпте Тестировщика — но не в регулярке:
// голая пометка проходила. Разбор стадии Тестировщика 21.10.2026 нашёл асимметрию с
// `secret-scan`, где оговорка без причины не считается (`lib/secrets.mjs`, тот же вид
// регулярки). Правило, обещанное тремя текстами и не исполняемое ни одним из них, — это
// снятая защита, о которой все думают, что она стоит.
const EXEMPT = /firm2:\s*стадийная проверка\s*[—-]\s*\S/i
// Голая пометка — отдельный случай: роль пометила, но причину не назвала, и сказать ей надо
// именно это, а не «тест проверяет момент» (иначе она решит, что пометка не сработала).
const EXEMPT_BARE = /firm2:\s*стадийная проверка/i

// Что считать тестом. Признак нарочно широкий и по ИМЕНИ, а не по содержимому: правило
// касается файлов, которые остаются в ветке поставки навсегда, и такие файлы во всех
// стеках маршрута лежат либо в tests/, либо названы по соглашению.
function looksLikeTest(file) {
  const posix = file.replace(/\\/g, '/')
  if (/(^|\/)tests?\//i.test(posix)) return true
  const base = posix.split('/').pop() || ''
  return /^test[_.]|[_.]test\.|\.spec\./i.test(base)
}

// Тикет для события. Спрашивается у ВЕТКИ того дерева, куда пишется файл: стадия работает
// в рабочем дереве задачи, и ветка там — `task/T-XXX`. Не нашлось — `MR`, а НЕ `unknown`:
// `unknown` в журнале это дыра (И-7), она краснит `doctor` навсегда, а журнал иммутабелен
// (ADR-0003/0006). Учёт пометки не должен стоить проекту вечно красной сверки.
function ticketOf(file, root) {
  for (const cwd of [file ? dirname(file) : null, root]) {
    if (!cwd) continue
    try {
      const branch = execFileSync('git', ['-C', cwd, 'rev-parse', '--abbrev-ref', 'HEAD'], {
        encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],
      }).trim()
      const t = ticketFromBranch(branch)
      if (t) return t
    } catch {
      // нет git в этом каталоге — пробуем следующий
    }
  }
  return 'MR'
}

function payload() {
  try {
    return JSON.parse(readFileSync(0, 'utf8'))
  } catch {
    return null
  }
}

function main() {
  const h = payload()
  if (!h) process.exit(0) // нет нагрузки — не наше дело, молчим

  const file = (h.tool_input && (h.tool_input.file_path || h.tool_input.filePath)) || ''
  if (!file || !looksLikeTest(file)) process.exit(0)

  // Правило принадлежит маршруту firm2: в чужом проекте хук плагина молчит.
  const root = repoRoot(process.env.CLAUDE_PROJECT_DIR || process.cwd())
  if (!root) process.exit(0)
  const cfg = readConfig(root)
  if (!cfg || cfg.engine !== 'firm2') process.exit(0)
  if (String((cfg.guard && cfg.guard.test_criteria) || 'on') === 'off') process.exit(0)

  // Write кладёт `content`, Edit — `new_string`. Проверяется только то, что пишется
  // СЕЙЧАС: существующий файл мог быть написан до этой защиты, и отказывать в правке
  // такого файла значило бы запирать его починку.
  const ti = h.tool_input || {}
  const text = String(ti.content || ti.new_string || ti.newString || '')
  if (!text) process.exit(0)

  // Пометка считается и на СТРОКЕ ВЫШЕ: комментарий естественно ставят над кодом, а не
  // в его хвосте. Проверено на себе — первая редакция смотрела только саму строку и
  // отвергала пример из собственной подсказки.
  const found = []
  const waived = []
  const bare = []
  const lines = text.split('\n')
  lines.forEach((line, i) => {
    const near = (re) => re.test(line) || (i > 0 && re.test(lines[i - 1]))
    const hits = SIGNS.filter((s) => s.re.test(line))
    if (!hits.length) return
    if (near(EXEMPT)) {
      waived.push({ n: i + 1, line: line.trim() })
      return
    }
    if (near(EXEMPT_BARE)) {
      bare.push({ n: i + 1, line: line.trim() })
      return
    }
    for (const s of hits) found.push({ n: i + 1, line: line.trim(), why: s.why })
  })

  // Пометка есть, причины нет. Отказываем, но говорим ровно про причину.
  if (!found.length && bare.length) {
    process.stderr.write(
      `[firm2] пометка стадийной проверки без причины: ${file}\n` +
        bare.map((b) => `  строка ${b.n}: ${b.line.slice(0, 100)}`).join('\n') + '\n\n' +
        'Пометка снимает защиту, поэтому обязана называть, почему здесь можно:\n' +
        '  # firm2: стадийная проверка — живёт один прогон, после слияния снимается\n' +
        'Без причины следующий читатель не узнает, законно ли это, — и защита держится ' +
        'только на вашем слове (тот же порядок, что у оговорки `firm2: не секрет`).\n',
    )
    process.exit(2)
  }

  // Пометка сработала. Пропускаем — и пишем событие: оговорка, о которой никто не узнал,
  // это снятая молча защита. Ровно так устроен `secret-scan`, и асимметрия между двумя
  // гвардами держалась до 0.4.90: семейство из пяти кругов могло вернуться через пометку,
  // не оставив следа ни в журнале, ни в `doctor`.
  if (!found.length && waived.length) {
    try {
      writeEvent(root, {
        ticket: ticketOf(file, root),
        stage: 'guard',
        event: 'test_criteria',
        actor: 'test-criteria-guard',
        notes:
          `стадийная проверка помечена с причиной, запись пропущена: ${file} — ` +
          waived.map((w) => `строка ${w.n}`).join(', '),
      })
    } catch {
      // Учёт не держит работу: не записалось — стадия всё равно идёт дальше (ADR-0014).
    }
    process.stderr.write(
      `[firm2] test-criteria-guard: ${waived.length} стадийн(ая/ые) проверка пропущена по пометке ` +
        'с причиной — запись прошла, пометка записана событием guard/test_criteria. ' +
        'После слияния задачи такую проверку снять.\n',
    )
    process.exit(0)
  }
  if (!found.length) process.exit(0)

  const what = found
    .slice(0, 5)
    .map((f) => `  строка ${f.n}: ${f.line.slice(0, 100)}\n    ↳ ${f.why}`)
    .join('\n')
  process.stderr.write(
    `[firm2] тест проверяет МОМЕНТ, а не поведение: ${file}\n${what}\n` +
      (found.length > 5 ? `  …и ещё ${found.length - 5}\n` : '') +
      `\nВечно живёт та проверка, которая даёт один и тот же ответ, сколько бы задач ни\n` +
      `легло сверху. Твоя зависит от лежащего поверх: после слияния точка ветвления\n` +
      `съезжает на коммит слияния, и диф «база..HEAD» показывает работу СЛЕДУЮЩЕЙ задачи.\n` +
      `Так «страж границ» T-039f заблокировал приёмку всей очереди — это семейство\n` +
      `BUG-043/045/046/047 и BUG-049, пять кругов одного дефекта.\n` +
      `\nЧто делать: проверяй СОСТОЯНИЕ дерева (файл существует, модуль не импортирует\n` +
      `запрещённое, схема сходится), а не разницу с какой-либо точкой истории.\n` +
      `\nЭто действительно проверка одного прогона, а не вечный тест? Помечай строку и\n` +
      `называй причину:\n` +
      `  # firm2: стадийная проверка — живёт один прогон, после слияния снимается\n`,
  )
  process.exit(2)
}

main()
