#!/usr/bin/env node
// Секрет не уезжает в коммит — отказ кодом, а не пункт в чек-листе (пункт 5 разбора ECC,
// `docs/ecc-ingest.md`).
//
// Почему этого не хватало. Движок закрывает ЧТЕНИЕ секретов: `.env` под песочницей
// нечитаем, `write-guard` не даёт писать куда попало. Но ключ попадает в историю другим
// путём — его вписывают руками или вставляют из вывода команды, которую стадия сама же и
// запустила. Удалением строки это не чинится: ключ остаётся в истории, и отзывать
// приходится сам ключ, то есть ломать всем окружение.
//
// Почему PreToolUse — и почему ЕЩЁ И git-хук. Git-хук обходится одним флагом
// (`--no-verify`), и обходит его та же роль, которой он мешает; PreToolUse отменяет сам
// вызов: `exit 2` — и коммита не было. Довод верен, но до 0.4.126 здесь стояло «вместо», и
// у выбранного места дыра оказалась больше: PreToolUse видит только то, что роль
// НАПЕЧАТАЛА подходящими словами, а git-хук видит каждый коммит, чем бы он ни был создан.
//
// Замер проект-В 04.11.2026: два события `guard/secret` с подписью «коммит ОТМЕНЁН», затем
// слияние — и те же три находки лежат в коммите `1e0285c9`. Сканер движка находит их в его
// диффе до сих пор, то есть дело не в снисхождении, а в пути, которым коммит прошёл.
// Признаком коммита была подстрока `git … commit`, поэтому `git merge --continue` и
// `git rebase --continue` — ровно то, что стадия запускает после конфликта, — были
// невидимы. Хуже того: по журналу нельзя узнать, сколько проходов сторож не увидел.
//
// Поэтому слоёв два, и дыры у них разные: PreToolUse отменяет вызов ДО работы и обходится
// незнакомой формой команды; `pre-commit` (шаблон `templates/git-hooks/pre-commit`, режим
// `--staged`) видит любой коммит и обходится `--no-verify`. Обойти оба одновременно можно
// только намеренно, и это уже не промах формы.
//
// Чего этот отказ НЕ делает. Он не ищет секреты в истории и не чинит уже уехавшее — это
// работа отзыва ключа. Он смотрит только на ДОБАВЛЕННЫЕ строки того диффа, который
// коммитится прямо сейчас.
//
// Проект, которому отказ мешает по делу, ослабляет его в `.firm/config`:
//
//   guard:
//     secret_scan: warn
//
// Тогда коммит проходит, но находка пишется событием `guard/secret` — то есть перестаёт
// быть невидимой. Любое другое значение ключа читается как `block`: неизвестность
// останавливает действие (И-12), иначе опечатка в конфиге молча снимала бы защиту.

import { readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { repoRoot, readConfig, writeEvent, ticketFromBranch, gitSubcommands } from './lib/firm.mjs'
import { findSecretsInDiff, targetDir } from './lib/secrets.mjs'

function readStdin() {
  try {
    return JSON.parse(readFileSync(0, 'utf8'))
  } catch {
    return null
  }
}

function git(cwd, args) {
  try {
    return execFileSync('git', ['-C', cwd, ...args], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
      // Дифф большой поставки упирается в стандартный буфер, и тогда `execFileSync`
      // бросает ENOBUFS — то есть проверка молча не выполнялась бы ровно на самых
      // объёмных коммитах.
      maxBuffer: 64 * 1024 * 1024,
      timeout: 20000,
    })
  } catch {
    return ''
  }
}

// Коммит ли это вообще — РАЗБОРОМ подкоманды, а не подстрокой. Прежний образец
// (`\bgit\b…\bcommit\b`) не видел ни одной формы, создающей коммит без этого слова, и
// первыми в том списке стоят продолжения после конфликта — именно их запускает стадия
// слияния (Д-48 проект-В 04.11.2026). Тот же разбор уже служит стражу расписки и стражу
// отправки, и третьего собственного образца здесь не нужно.
//
// `merge`/`rebase`/`cherry-pick` БЕЗ `--continue` сюда не входят намеренно: в индексе
// перед ними ничего не лежит, сверять нечего, а отказ на каждом слиянии был бы шумом.
// Их закрывает второй слой — git-хук `pre-commit`.
const CONTINUED = new Set(['merge', 'rebase', 'cherry-pick', 'revert', 'am'])

function createsCommit(cmd) {
  for (const g of gitSubcommands(cmd)) {
    if (g.sub === 'commit') return true
    if (CONTINUED.has(g.sub) && g.rest.some((r) => r === '--continue')) return true
  }
  return false
}

// `-a` / `--all` / `-am` берут в коммит и незастейдженное — значит смотреть надо не
// только `--cached`. Короткие флаги склеиваются (`-am`, `-sam`), поэтому ищем букву
// внутри группы коротких флагов, а не отдельное слово.
const ALL_FLAG = /(?:^|\s)--all\b|(?:^|\s)-[A-Za-z]*a[A-Za-z]*\b/


function main() {
  // Второй слой: вызов из git-хука `pre-commit`. Нагрузки на входе нет, дерево — то, в
  // котором коммитят, и возврат 1 (а не 2): это код git-хука, не хука рантайма.
  const staged = process.argv.includes('--staged')
  const h = staged ? { cwd: process.cwd() } : readStdin()
  if (!h) process.exit(0)

  const cmd = String((h.tool_input || {}).command || '')
  if (!staged && !createsCommit(cmd)) process.exit(0)

  const root = process.env.CLAUDE_PROJECT_DIR || repoRoot()
  if (!root) process.exit(0)
  const cfg = readConfig(root)
  if (!cfg || cfg.engine !== 'firm2') process.exit(0)

  // Дифф спрашиваем у того дерева, в которое КОММИТЯТ, а не у того, откуда позвали.
  // Разница не теоретическая: стадия обычно остаётся в каталоге сессии и коммитит через
  // `git -C <дерево задачи> commit`. До 0.4.98 хук брал `h.cwd`, то есть индекс ГЛАВНОГО
  // дерева, — и 23.10.2026 на проект-В трижды отменил коммит T-118 на находке из файлов
  // T-130, лежавших в индексе главного дерева от незакрытого мержа T-113. Дифф самой
  // T-118 секретоподобных строк не содержал (дефект O отчёта проекта).
  //
  // Цена ошибки двойная: работа, которая сделана, не коммитится, а оговоркой
  // «firm2: не секрет» это не лечится по устройству — строки лежат в файлах чужой задачи,
  // и пометить их стадия не может, она их не писала. Оттуда же шла и ложная привязка:
  // ветку хук читал тем же `cwd`, поэтому 16 из 18 событий прохода уехали на `MR`.
  const cwd = targetDir(cmd, h.cwd || process.cwd())

  let diff = git(cwd, ['diff', '--cached'])
  if (ALL_FLAG.test(cmd)) diff += `\n${git(cwd, ['diff', 'HEAD'])}`
  if (!diff.trim()) process.exit(0)

  let findings = findSecretsInDiff(diff)
  // У мержа родителей ДВА, и дифф к одному из них выдаёт за добавленное всё содержимое
  // второй ветки. Замер проект-В 04.11.2026 (Д-49), мерж `main` → `3d`, воспроизведён
  // здесь же: 21 блокирующая находка, и ни одной строки мерж не писал — все они годами
  // лежали в сливаемой ветке. Правок разрешения конфликтов, узнаваемых как секрет, было
  // НОЛЬ при 89 конфликтных файлах, то есть верный ответ сторожа на этом мерже — «чисто».
  //
  // Лечение оговоркой здесь не лечит по устройству: строки лежат в файлах чужой линии,
  // пометить их значит правкой чужой работы внутри мержа, и следующий мерж придёт с теми
  // же строками снова. Проект платил 21 строкой разметки в 19 файлах НА КАЖДУЮ линию.
  //
  // Поэтому на мерже судим только то, что мерж написал САМ: строку, которой нет ни в
  // одном из родителей. Это в точности правки разрешения конфликтов — единственное, что
  // в мерже пишется руками, и единственное, за что мерж отвечает. Признак мержа доступен
  // до коммита: `MERGE_HEAD` (он же стоит и у `git merge --continue`).
  const second = git(cwd, ['rev-parse', '--verify', '--quiet', 'MERGE_HEAD']).trim()
  const merge = { on: Boolean(second), dropped: 0 }
  if (merge.on && findings.length) {
    const key = (f) => `${f.file}|${f.line}`
    // Вторая сторона сравнения — тот же индекс против ВТОРОГО родителя. Строка, пришедшая
    // из второй ветки, в этом диффе добавленной не окажется; строка, написанная
    // разрешением конфликта, окажется добавленной в обоих.
    const inSecond = new Set(findSecretsInDiff(git(cwd, ['diff', '--cached', second])).map(key))
    const own = findings.filter((f) => inSecond.has(key(f)))
    merge.dropped = findings.length - own.length
    findings = own
  }
  if (!findings.length) {
    // Сказать об этом в журнал НЕЧЕГО: мерж чист, а событие на каждый чистый мерж — шум.
    // Роли сказать стоит: иначе «сторож промолчал» читается как «сторож не сработал».
    if (merge.dropped) {
      process.stderr.write(
        `[firm2] secret-scan: мерж, и ${merge.dropped} секретоподобн(ых) находок пришли СО ВТОРОЙ\n` +
          'ветки — их писал не этот коммит. Мерж судится за своё: за правки разрешения\n' +
          'конфликтов. Своих находок нет, коммит проходит (Д-49).\n',
      )
    }
    process.exit(0)
  }

  const blocking = findings.filter((f) => !f.waived)
  const waived = findings.filter((f) => f.waived)
  const branch = git(cwd, ['rev-parse', '--abbrev-ref', 'HEAD']).trim()
  // Вне ветки задачи — `MR`, а НЕ `unknown`. `unknown` в журнале означает дыру привязки
  // (И-7) и краснит `doctor` НАВСЕГДА: журнал иммутабелен (ADR-0003/0006), а снимается
  // такая находка только отдельным событием аннулирования. То есть один помеченный
  // ложный секрет в коммите на `main` стоил бы проекту вечно красной сверки. Решение
  // принято для расписок об отправке (0.4.84, ADR-0014) и здесь не было донесено —
  // найдено разбором стадии Тестировщика 21.10.2026.
  const ticket = ticketFromBranch(branch) || 'MR'
  const mode = String((cfg.guard && cfg.guard.secret_scan) || 'block') === 'warn' ? 'warn' : 'block'
  // В СОБЫТИЕ находка идёт именем файла и номером строки, без цитаты. Цитата в журнале
  // кормит следующую сверку: на проект-В 04.11.2026 две отмены из трёх находок были найдены
  // в событиях ПРЕДЫДУЩИХ отмен, которые цитировали первую. Поверхность росла на файл за
  // попытку, и остановить это могло только исключение журнала — то есть оба лечения нужны
  // по отдельности. Роли цитата по-прежнему печатается в stderr: там она живёт один вызов.
  const list = (items) => items.map((f) => `${f.file}:${f.line_no ?? '?'} ${f.rule}`).join('; ')

  if (!blocking.length) {
    // Все находки помечены оговоркой. Пропускаем, но событие пишем: оговорка, о которой
    // никто не узнал, — это снятая молча защита.
    writeEvent(root, {
      ticket,
      stage: 'guard',
      event: 'secret',
      actor: 'secret-scan',
      notes: `находки помечены оговоркой «firm2: не секрет», коммит пропущен: ${list(waived)}`,
    })
    process.stderr.write(
      `[firm2] secret-scan: ${waived.length} находк(и) помечены оговоркой «firm2: не секрет» — ` +
        'коммит пропущен, оговорка записана событием guard/secret.\n',
    )
    process.exit(0)
  }

  writeEvent(root, {
    ticket,
    stage: 'guard',
    event: 'secret',
    actor: 'secret-scan',
    notes:
      `${mode === 'warn' ? 'guard.secret_scan: warn — коммит пропущен' : 'коммит ОТМЕНЁН'}: ` +
      list(blocking),
  })

  if (mode === 'warn') {
    process.stderr.write(
      `[firm2] secret-scan: похоже на секрет в коммите (${blocking.length}). Проект разрешил это\n` +
        'ключом guard.secret_scan: warn, поэтому коммит пропущен — и записан событием guard/secret.\n' +
        `${blocking.map((f) => `  · ${f.file}: ${f.rule} — ${f.excerpt}`).join('\n')}\n`,
    )
    process.exit(0)
  }

  process.stderr.write(
    `[firm2] В коммит едет то, что похоже на СЕКРЕТ (${blocking.length}). ` +
      `${staged ? 'Коммит остановлен git-хуком.' : 'Вызов отменён.'}\n` +
      `${blocking.map((f) => `  · ${f.file}: ${f.rule}\n    ${f.excerpt}`).join('\n')}\n` +
      'Строка в репозитории не отзывается удалением строки: ключ остаётся в истории, и\n' +
      'отзывать придётся сам ключ — то есть ломать окружение всем.\n' +
      'Что делать:\n' +
      '  • значение убрать из кода, читать из окружения одной точкой чтения настроек;\n' +
      '  • тестам дать фикстуру, которая ключом не является (заглушка, а не рабочий ключ);\n' +
      '  • если ключ уже уехал в прошлый коммит — скажи об этом человеку в notes прямо\n' +
      '    сейчас: отзыв ключа делает он, и чем раньше узнает, тем дешевле;\n' +
      '  • находка ЛОЖНАЯ (образец узнал ключ там, где его нет) — пометь строку оговоркой\n' +
      '    с причиной, и коммит пройдёт: `# firm2: не секрет — тестовый вектор из RFC 7515`.\n' +
      '    Оговорка без причины не считается, и каждая попадает в журнал событием.\n' +
      (staged ? '' :
        'И про сам вызов: отмена уносит КОМПАУНД целиком, то есть `git add -A && git commit`\n' +
        'не выполнит и `git add`. Оговорки окажутся в дереве, но не в индексе, и повторный\n' +
        'отказ прочтётся как «оговорки не помогли». Индексируй ОТДЕЛЬНЫМ вызовом (Д-49).\n') +
      (merge.on && merge.dropped ? `Это мерж, и находок со второй ветки отброшено ${merge.dropped}: ` +
        'их писал не этот коммит. Перечисленное выше мерж написал САМ.\n' : '') +
      'Упомяни этот отказ в notes: он объясняет, почему шаг не сделан.\n',
  )
  // Два слоя — два кода возврата. `exit 2` понимает рантайм (вызов отменён и роль читает
  // stderr), `exit 1` — git (коммита не будет). Перепутать их значит получить проход.
  process.exit(staged ? 1 : 2)
}

main()
