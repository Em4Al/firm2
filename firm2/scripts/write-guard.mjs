#!/usr/bin/env node
// Защита главного рабочего дерева от записи стадии (Д-4 разбора 23.09.2026).
//
// Что случилось. Тестировщик T-105 записал оба своих теста по ОТНОСИТЕЛЬНОМУ пути
// (`tests/test_t105_*.py`), и они ушли в главное дерево вместо рабочего дерева задачи.
// Слияние после этого отказало — «untracked working tree files would be overwritten» —
// и разбирать это пришлось человеку. Запрет в промпте стадии был, но он словесный:
// относительный путь пишется не по злому умыслу, а по невнимательности, и словами
// такое не ловится.
//
// Правило. Пока в проекте есть ХОТЯ БЫ ОДНО живое рабочее дерево задачи, запись по пути
// внутри главного дерева запрещена — кроме каталогов, которые по устройству маршрута
// принадлежат не задаче, а поставке:
//
//   .firm/      журнал событий, дашборд, claim-файлы — их пишет движок;
//   openspec/   спеки, задачи, proposal — их ведут PM и Архитектор;
//   docs/       BRD, ADR, диаграммы, прототип, баги — они переживают поставку;
//   .claude/    настройки проекта — их правит firm-permissions.
//
// Почему именно «есть живое дерево», а не «агент — стадия». Роль в полезной нагрузке
// PreToolUse не гарантирована, а живое дерево задачи — надёжный признак того, что идёт
// сборка: до неё деревьев нет, после слияния шаг уборки их сносит. В эту же пору
// оркестратор исходники в главном дереве не пишет — он запускает команды, а его
// собственные записи попадают в каталоги из списка выше.
//
// Рабочие деревья лежат ВНЕ репозитория (§9), поэтому запись в них под правило не
// подпадает вовсе: путь просто не внутри главного дерева.
//
// И ещё одно исключение, не по каталогу, а по СОСТОЯНИЮ: пока в главном дереве не закрыта
// операция git (слияние с конфликтом, rebase, cherry-pick, revert), запись разрешена — см.
// `gitOperationInProgress`. Разрешение конфликта по устройству маршрута происходит именно
// в главном дереве, и без этого исключения два правила движка упирались друг в друга.
//
// Аварийный выход — в `.firm/config`:
//   guard:
//     write_outside_worktree: off
// Он нужен на случай, который здесь не предусмотрен. Отключение видно в конфиге, а не
// спрятано в коде: молчаливо снятая защита хуже отсутствующей.
//
// Журнала событий рубильник НЕ открывает — см. `JOURNAL_DIR` ниже: там запрет про другое.

import { execFileSync } from 'node:child_process'
import { readFileSync, realpathSync, existsSync } from 'node:fs'
import { resolve, relative, isAbsolute, dirname, sep } from 'node:path'
import { repoRoot, readConfig, listWorktrees, ticketFromBranch } from './lib/firm.mjs'

// Пути приводим к реальным, иначе сравнение врёт. На macOS `/tmp` — симлинк на
// `/private/tmp`, и путь из полезной нагрузки хука может прийти через один, а корень
// репозитория определиться через другой: `relative` тогда даёт `..`, и защита молча
// пропускает всё. Найдено собственным тестом, а не рассуждением.
// Файла ещё нет (его как раз собираются создать), поэтому разрешаем ближайшего
// существующего предка и дописываем хвост обратно.
function realish(p) {
  let head = resolve(p)
  const tail = []
  for (;;) {
    try {
      return tail.length ? resolve(realpathSync(head), ...tail) : realpathSync(head)
    } catch {
      const up = dirname(head)
      if (up === head) return resolve(p)
      tail.unshift(head.slice(up.length + 1))
      head = up
    }
  }
}

// Каталоги поставки, а не задачи. Слэш на конце обязателен: без него `docsy/` прошёл бы
// как `docs`.
const DELIVERY_DIRS = ['.firm/', 'openspec/', 'docs/', '.claude/']

// Исключение внутри разрешённого: журнал событий. `.firm/` разрешён целиком потому, что его
// пишет движок, — но из всего `.firm/` движок пишет событиями ровно `events/`, и пишет их
// своим кодом (ADR-0002), а не инструментом записи роли. Значит всякая запись сюда ИНСТРУМЕНТОМ
// — это стадия, правящая историю руками: сам движок через этот хук не проходит вовсе
// (PreToolUse видит только вызовы инструментов агента).
//
// Инвариант И-2 и ADR-0006 держались здесь случайно — тем, что никто не пробовал. Найдено
// ревью 01.10.2026 в списке «чего проверить не удалось»; закрыто 02.10.2026 до первого случая,
// потому что случай был бы невидим: отредактированное руками событие остаётся синтаксически
// правильным, журнал просто перестаёт быть историей, и `doctor` на это ничего не скажет.
const JOURNAL_DIR = '.firm/events/'

// Незакрытая операция git в ГЛАВНОМ дереве: слияние с конфликтом, rebase, cherry-pick,
// revert. Пока она не закрыта, запись в главное дерево — работа Оркестратора, а не стадии,
// и запрещать её нельзя.
//
// Это противоречие двух правил движка, и нашла его сессия проект-Г 02.10.2026:
// «запись только в рабочее дерево задачи» и «конфликт слияния разрешается в главном дереве»
// упирались друг в друга. Выйти удалось, только сняв рабочие деревья заранее, — а при живых
// параллельных задачах снимать их нельзя, то есть выхода не было бы вовсе.
//
// Признак берём у git, а не у роли и не у времени: состояние незакрытой операции git держит
// сам, оно проверяемо и кончается вместе с операцией. Окно получается узким по существу, а
// не по доверию: закрыл слияние — защита вернулась в ту же секунду.
//
// Почему не «разрешить ровно конфликтующие файлы»: после `git add` файл уходит из списка
// неслитых, и повторная правка того же файла была бы снова запрещена — посреди разрешения
// конфликта. Это вернуло бы то же трение в середину операции.
function gitOperationInProgress(root) {
  const q = (...a) => {
    try {
      return execFileSync('git', ['-C', root, ...a], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
    } catch {
      return ''
    }
  }
  for (const ref of ['MERGE_HEAD', 'CHERRY_PICK_HEAD', 'REVERT_HEAD', 'REBASE_HEAD']) {
    if (q('rev-parse', '-q', '--verify', ref)) return ref
  }
  // Каталоги rebase и заготовки сообщения. `SQUASH_MSG` здесь не для полноты: у
  // `git merge --squash` нет `MERGE_HEAD`, и без этого признака окно закрывалось бы по
  // неслитым файлам — то есть в момент `git add`, а не коммита, и защита возвращалась бы
  // РАНЬШЕ, чем человек закончил. Проверено: `SQUASH_MSG` git заводит сам и сам удаляет при
  // коммите, то есть он того же свойства, что `MERGE_HEAD`, — состояние, а не наш домысел.
  // Замечание тестировщика 02.10.2026, и оно верное.
  for (const d of ['rebase-merge', 'rebase-apply', 'SQUASH_MSG', 'MERGE_MSG']) {
    const path = q('rev-parse', '--git-path', d)
    if (path && existsSync(resolve(root, path))) return d
  }
  // Последним — неслитые файлы в индексе: признак, который снимает не git, а тот, кто
  // разрешает конфликт (`git add`). Поэтому он и последний: все признаки выше кончаются
  // вместе с операцией, этот — раньше. Оставлен как сеть на случай, который перечислением
  // не покрыт.
  if (q('diff', '--name-only', '--diff-filter=U')) return 'неслитые файлы в индексе'
  return null
}

function readStdin() {
  try {
    return JSON.parse(readFileSync(0, 'utf8'))
  } catch {
    return null
  }
}

function main() {
  const h = readStdin()
  if (!h) process.exit(0) // нет нагрузки — не наше дело, молчим

  const file = (h.tool_input && (h.tool_input.file_path || h.tool_input.filePath)) || ''
  if (!file) process.exit(0)

  const root = process.env.CLAUDE_PROJECT_DIR || repoRoot()
  if (!root) process.exit(0)

  const cfg = readConfig(root)
  if (!cfg || cfg.engine !== 'firm2') process.exit(0)
  // Относительный путь разрешаем от cwd вызова — именно так его понял бы инструмент.
  const base = h.cwd || process.cwd()
  const abs = realish(isAbsolute(file) ? file : resolve(base, file))

  const rel = relative(realish(root), abs)
  // Пустой, с `..` или абсолютный — путь вне главного дерева. Рабочие деревья задач
  // лежат именно там, и это нормальный случай, ради которого всё и затевалось.
  if (!rel || rel.startsWith('..') || isAbsolute(rel)) process.exit(0)

  const posix = rel.split(sep).join('/')

  // Сначала запрет, потом разрешение: иначе `.firm/` пропустит журнал первым же правилом.
  if (posix === JOURNAL_DIR.slice(0, -1) || posix.startsWith(JOURNAL_DIR)) {
    process.stderr.write(
      `[firm2] запись в журнал событий инструментом запрещена: ${posix}\n` +
        `События переходов пишет КОД движка, а не стадия (ADR-0002), и журнал только\n` +
        `дописывается: исправление и аннулирование — тоже событие, а не правка файла\n` +
        `(ADR-0006, инвариант И-2). Отредактированное руками событие остаётся правильным\n` +
        `на вид, поэтому ни \`doctor\`, ни ревью такую правку потом не найдут.\n` +
        `\n` +
        `Что нужно вместо этого:\n` +
        `  событие о факте        node <engine_root>/scripts/firm-event.mjs record \\\n` +
        `                           --ticket T-XXX --stage <стадия> --event <событие> --notes '…'\n` +
        `  прежнее событие неверно  тот же record --event retracted --corrects <файл> --notes 'почему'\n` +
        `\n` +
        `Остальной \`.firm/\` (конфиг, дашборд, claim-файлы) не запрещён — только \`events/\`.\n`,
    )
    process.exit(2)
  }

  // Незакрытая операция git — выше всех остальных разрешений, но НИЖЕ запрета журнала:
  // иммутабельность истории конфликтом не отменяется (а конфликтовать файлам событий и
  // не из чего — один файл на событие, ADR-0003).
  const op = gitOperationInProgress(root)
  if (op) process.exit(0)

  // Аварийный выход — НИЖЕ запрета журнала и выше всего остального. Рубильник снимает ровно
  // одну защиту — «чья это работа сейчас»: она про текущую сборку и потому законно снимается
  // на время. Иммутабельность журнала (И-2) — про другое и исключений не знает: её нельзя
  // снять «на время», потому что переписанное событие остаётся переписанным навсегда.
  // Найдено тестировщиком 02.10.2026: из порядка строк выходило, что один рубильник открывает
  // оба запрета — то есть ровно то, чего быть не должно.
  // Человеку рубильник для журнала и не нужен: хук видит только вызовы инструментов агента,
  // а своим редактором человек правит файлы мимо него.
  const guard = (cfg.guard && cfg.guard.write_outside_worktree) || 'on'
  if (String(guard) === 'off') process.exit(0)

  if (DELIVERY_DIRS.some((d) => posix === d.slice(0, -1) || posix.startsWith(d))) process.exit(0)

  // `git worktree list` показывает и деревья, от которых остался только след: шаг уборки
  // снёс каталог, но не позвал `worktree prune`. Такое дерево помечено prunable, и для
  // защиты оно — ложное «идёт сборка»: каталога нет, писать стадии некуда, а запись в
  // главное дерево была бы запрещена навсегда. Считаем живым только существующий каталог.
  // (Наблюдено в проект-Б 23.09.2026: T-102 висел prunable после слияния.)
  const live = listWorktrees(root)
    .filter((w) => ticketFromBranch(w.branch))
    .filter((w) => realish(w.path) !== realish(root))
    .filter((w) => existsSync(w.path))
  if (!live.length) process.exit(0)

  const where = live.map((w) => `  ${ticketFromBranch(w.branch)} → ${w.path}`).join('\n')
  process.stderr.write(
    `[firm2] запись в ГЛАВНОЕ рабочее дерево запрещена, пока идёт сборка: ${posix}\n` +
      `Путь разрешился в ${abs} — это главное дерево, а не рабочее дерево твоей задачи.\n` +
      `Почти всегда причина одна: путь указан относительным. Пиши по АБСОЛЮТНОМУ пути\n` +
      `внутрь своего рабочего дерева. Сейчас живы:\n${where}\n` +
      `Файл, записанный сюда, в слияние не попадёт и сорвёт его: так на T-105 два теста\n` +
      `ушли мимо ветки, и разбирать пришлось человеку.\n` +
      `Правка действительно нужна в главном дереве (спека, журнал, документация) —\n` +
      `её каталоги разрешены: .firm/, openspec/, docs/, .claude/. Всё остальное —\n` +
      `в рабочее дерево задачи.\n`,
  )
  process.exit(2)
}

main()
