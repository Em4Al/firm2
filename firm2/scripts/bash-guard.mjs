// делать в своём же отказе по долгому ожиданию. Стадия PM нашла обход за один ход
// (`uv run python -m pytest`), и это главный довод: правило, которое платится только теми,
// кто делает по инструкции, правилом не является.
//
// Остаточная дыра названа вслух: вызов, не содержащий ни одной из двух команд проекта
// (`python -m pytest` вместо `uv run pytest`), сторож не опознаёт вовсе. Закрыть её можно
// только угадыванием запускателя по имени, а угадывание здесь дороже дыры: ложный отказ
// бьёт по честной работе, а обход — по учёту, который и так виден замером `stage-bill`.
const NARROWING = [
  /(^|\s)-k(\s|=)/, // pytest, jest: выбор по имени
  /(^|\s)-m(\s|=)/, // pytest: выбор по метке
  /(^|\s)-t(\s|=)/, // node --test, mocha: имя теста
  /::/, // pytest: конкретный тест в файле
  /--ignore/, /--deselect/, /--test-name-pattern/, /--testNamePattern/,
  /--testPathPattern/, /--grep/, /--filter/, /--only/, /--last-failed/, /--lf\b/,
  /(^|\s)[^\s-][^\s]*\.(py|mjs|cjs|js|jsx|ts|tsx|rb|go|rs|java|kt|php)(\s|$)/, // путь до файла
  /(^|\s)[^\s-][^\s]*\/[^\s]*(\s|$)/, // путь до каталога или файла без расширения
]

function narrowed(tail) {
  return NARROWING.some((re) => re.test(tail))
}

function fullSuite(cmd, cfg) {
  const stack = cfg.stack || {}
  const full = typeof stack.test_cmd === 'string' ? stack.test_cmd.trim() : ''
  const task = typeof stack.task_test_cmd === 'string' ? stack.task_test_cmd.trim() : ''
  if (!full || !task || full === task) return null
  const line = String(cmd || '').replace(/\s+/g, ' ').trim()
  if (!line) return null
  const norm = (s) => s.replace(/\s+/g, ' ')
  // Задачная команда — ровно то, что велено гнать. Совпала — речи нет, и проверять в ней
  // сужение нельзя: её собственные `--ignore` стоят до конца строки, хвоста за ними нет.
  if (line.includes(norm(task))) return null
  // Иначе вызов про набор лишь тогда, когда содержит полную команду проекта.
  const mark = norm(full)
  if (!line.includes(mark)) return null
  // Сужение ищем в ХВОСТЕ — в том, что роль добавила к команде проекта сама.
  const tail = line.slice(line.indexOf(mark) + mark.length)
  if (narrowed(tail)) return null
  return { full, task }
}

// Тикет вызова — по рабочему дереву, а если его нет, по ЯРЛЫКУ вызова подагента.
//
// Отчёт проект-В 02.11.2026 (находка 1): события `guard/full-suite` уезжали с
// `ticket: "unknown"` ВСЕГДА, не иногда. Полный прогон по замыслу идёт с ворот поставки, то
// есть из главного дерева, где дерева задачи нет вовсе — а `doctor` считает события без
// тикета дырой и краснеет. Выходило, что санкционированный обход, применённый строго по
// инструкции, портит журнал.
//
// Второй источник — тот же, что у привязки стартов (Д-44): маркер в транскрипте подагента,
// а на старте ярлык вызова из мета-файла. Стадия в этот момент уже идёт, поэтому маркер
// обычно на месте, и ответ приходит без догадок — из полей, которые в нагрузке уже есть.
function ticketOf(root, cwd, h = null) {
  for (const w of listWorktrees(root)) {
    const t = ticketFromBranch(w.branch)
    if (!t || !cwd) continue
    const rel = relative(w.path, cwd)
    if (!rel || (!rel.startsWith('..') && !isAbsolute(rel))) return t
  }
  if (h && h.session_id && h.agent_id) {
    const m = markerFromAgent(root, h.session_id, h.agent_id)
    if (m && m.ticket) return m.ticket
  }
  return 'unknown'
}

// Ворота поставки — не стадия задачи, и правила стадии к ним не применяются.
//
// Отчёт проект-В 02.11.2026 (Д-44б и находка 2): признак стадии — любой подагент, а шаг 3б
// маршрут выполняет подагентом упаковки. Выходило, что потолок запрещает полный прогон
// ровно в том месте, куда сам отсылает отказом, и правило долгого ожидания отклоняет живой
// браузерный гейт, который короче 62 минут не бывает. Проекту это стоило правки
// `.firm/config` на время упаковки — обход, который забудешь снять, и потолка не станет на
// всей следующей волне.
//
// Признак ворот — тикет `MR`: маркер `FIRM2-TICKET: MR` в промпте стадий уровня поставки
// рубеж проверяет отдельным шагом, так что это не догадка, а наш собственный контракт.
function atGate(ticket) {
  return ticket === 'MR'
}

