import { readFileSync, existsSync } from 'node:fs'
import { resolve, relative, isAbsolute } from 'node:path'
import { repoRoot, readConfig, writeEvent, worktreesDir, listWorktrees, ticketFromBranch, isEngineTree, markerFromAgent } from './lib/firm.mjs'

function readStdin() {
  try {
    return JSON.parse(readFileSync(0, 'utf8'))
  } catch {
    return null
  }
}

// Внутри ли путь каталога рабочих деревьев. Сравниваем по разобранному пути, а не по
// строке: `../repo.worktrees` из конфига и абсолютный `cwd` вызова — это одно место,
// записанное двумя способами.
function insideWorktrees(root, cwd) {
  if (!cwd) return null
  const abs = isAbsolute(cwd) ? cwd : resolve(root, cwd)
  const dir = worktreesDir(root, readConfig(root) || {})
  if (dir) {
    const rel = relative(dir, abs)
    if (rel && !rel.startsWith('..') && !isAbsolute(rel)) return serviceTree(root, abs) ? null : abs
    if (abs === dir) return abs
  }
  // Запасной признак: дерево может лежать и не под `worktrees_dir` — например заведённое
  // руками. Спрашиваем git, какие деревья он знает, и сверяем с ними.
  for (const w of listWorktrees(root)) {
    if (!ticketFromBranch(w.branch)) continue
    if (!existsSync(w.path)) continue
    const rel = relative(w.path, abs)
    if (!rel || (!rel.startsWith('..') && !isAbsolute(rel))) return abs
  }
  return null
}

// Служебное дерево движка, выгруженное на НЕ задачную ветку: `_trunk` на ветке-цели,
// `_merge3d` на ветке поставки, `_demo` на показе. Это места ЧЕЛОВЕКА и Оркестратора, а не
// стадий, и признак «cwd внутри worktrees_dir» ловит в них ровно того, кого маршрут туда и
// послал.
//
// Отчёт проект-В 08.11.2026 (Д-60). Шаг 6 маршрута — вливание и выпуск — обязан идти там, где
// выгружена ветка-цель, а это `проект-В.worktrees/_trunk` (раскладка, которую движок сам
// называет штатной и `prune` намеренно не трогает). Оркестратор пришёл туда по устройству
// маршрута, попробовал `git push` под песочницей (не вышло: закрыт конфиг `gh`), повторил
// со снятием — и получил «снятие песочницы стадией ЗАПРЕЩЕНО». `cd` внутри команды признака
// не меняет: хук читает ПОСТОЯННЫЙ рабочий каталог оболочки. То есть решение, которое по
// тексту самого отказа принимает человек, стало недоступно и человеку.
//
// Это та же дыра, что Д-39, только в другую сторону: там стадия работала из главного дерева
// и признак по дереву её не видел, здесь не-стадия работает из дерева и признак видит её
// стадией. Чиним тем же, чем Д-39: стадию в служебном дереве опознаёт СИЛЬНЫЙ признак —
// агентские поля нагрузки (`fromSubagent`), и он здесь остаётся единственным.
//
// `_base` под это НЕ попадает намеренно: дерево основания сверки стоит `--detach`, ветки у
// него нет, и работает в нём именно стадия (зонд точки ветвления). Отсекаем только дерево с
// названной не задачной веткой — то есть место, куда ветку выгрузил человек или маршрут.
//
// Ключ — ВЕТКА, и ветка из закрытого списка; имя каталога ключом не служит. Уточнение от
// 08.11.2026 по замеру проект-В: в живом каталоге рабочих деревьев рядом с `_trunk` и `_base`
// лежит `backlog-F-032` на ветке `backlog/F-032` — дерево темы разведки, где по долгу
// работают и роли, и человек, и Оркестратор. По имени оно не служебное, по ветке — не
// задачное, и ключ «имя с подчёркивания» дал бы на него обратный ответ.
//
// Отпускаются ровно те ветки, которые в дерево выгружает САМ МАРШРУТ и в которых работает
// сессия, а не стадия: ветка-цель (шаг 6 — вливание и выпуск), `backlog/*` (тема разведки) и
// `feature/*` (поставка: демо, разбор, слияние вручную). Всё прочее остаётся стадией по
// каталогу — в том числе дерево задачи, переключённое на свою ветку (`scratch/...`): такая
// ветка маршрутом не выдаётся, и считать её местом человека не за что.
//
// Цена названа вслух: на рантайме, который агентских полей не кладёт, стадия разведки в
// дереве темы снимет песочницу беспрепятственно. Это та же дыра, что была у Д-39 в главном
// дереве, и закрывается она тем же — полями, а не каталогом; делать вид, что каталог её
// закрывает, значило бы держать отказ, который ловит человека чаще, чем стадию.
function serviceTree(root, cwd) {
  if (!cwd) return null
  const abs = isAbsolute(cwd) ? cwd : resolve(root, cwd)
  let best = null
  for (const w of listWorktrees(root)) {
    if (w.path === root) continue // главное дерево — не «дерево рядом с задачами», у него свой текст
    const rel = relative(w.path, abs)
    if (!rel || (!rel.startsWith('..') && !isAbsolute(rel))) {
      if (!best || w.path.length > best.path.length) best = w
    }
  }
  if (!best || !best.branch) return null // git дерева не знает или оно detached — не ослабляем
  if (ticketFromBranch(best.branch)) return null // дерево задачи остаётся деревом задачи
  return routeBranch(root, best.branch) ? best.path : null
}

// Ветка, которую в дерево выгружает маршрут, а не стадия. Имя ветки-цели берём из конфига
// (`main_branch`), иначе по факту — `main`/`master`: то же правило, по которому её называет
// `build-args`, и расходиться им нельзя.
function routeBranch(root, branch) {
  const b = String(branch || '')
  const cfg = readConfig(root) || {}
  const target = cfg.main_branch ? String(cfg.main_branch) : null
  if (target ? b === target : (b === 'main' || b === 'master')) return true
  return /^(backlog|feature)\//.test(b)
}

// Пришёл ли вызов ОТ ПОДАГЕНТА, то есть от стадии. Признак не зависит от `cwd` — в этом
// весь смысл: `cwd` стадии может быть главным деревом (так и было на Д-39), и тогда признак
// по дереву её не видит. Полезная нагрузка `PreToolUse` формат чужой, поля про агента в ней
// не гарантированы (тот же довод, что в `write-guard.mjs`), поэтому спрашиваем все известные
// и переменную окружения, которой пользуется `firm-event.mjs claim`. Признак используется
// ТОЛЬКО на сужение: нашли — считаем стадией, не нашли — остаётся прежний признак по дереву.
function fromSubagent(h) {
  if (!h) return false
  if (h.agent_id || h.agent_type || h.subagent_type || h.agent_transcript_path) return true
  return Boolean(process.env.CLAUDE_AGENT_ID)
}

// Разрушающая команда по служебному каталогу git. Границу после `.git` держим строго: иначе
// под запрет попадают `.gitignore`, `.gitconfig` и `.github`, к которым правило отношения не
// имеет. Возвращаем первый найденный путь — он идёт в текст отказа, чтобы человек видел, на
// что именно сторож сработал, а не спорил с регуляркой.
const GIT_PATH = /(?:^|[\s'"=(])((?:[^\s'";|&]*\/)?\.git(?![\w.-])(?:\/[^\s'";|&]*)?)/g
function gitSurgery(cmd) {
  const c = String(cmd || '')
  const destructive = /\b(rm|rmdir|unlink|truncate|shred)\b/.test(c) || /\bmv\b/.test(c) || /\bfind\b[^\n]*-delete/.test(c)
  if (!destructive) return null
  // Путь к служебному каталогу можно и не писать буквами: `$(git rev-parse --git-dir)`,
  // `--git-dir`, `$GIT_DIR` — то же место, названное через git. Разрушение по такому
  // выражению ничем не отличается от разрушения по `.git/`.
  if (/--git-dir|rev-parse\s+--git-dir|\$GIT_DIR|\$\{GIT_DIR/.test(c)) return 'служебный каталог git (выражение git-dir)'
  for (const m of c.matchAll(GIT_PATH)) {
    const p = m[1]
    if (p === '.git' || p.endsWith('/.git') || p.includes('.git/')) return p
  }
  return null
}

// Деревья ДВИЖКА (`_trunk`, `_base`) — не стадии. Длинные прогоны живут именно там: это
// их работа, снятая один раз на волну, и запрещать им ожидание значит запрещать сам
// механизм, ради которого они заведены.
function engineTree(abs) {
  const parts = String(abs || '').split('/')
  return parts.some((x) => isEngineTree(x))
}

// Сколько секунд команда намерена ПРОСПАТЬ. Считаем грубо и в сторону запрета только там,
// где намерение видно в самой команде: `sleep N` в цикле с известным числом оборотов, цикл
// без границы вовсе, одиночный долгий `sleep`. Неизвестное число оборотов — это НЕ ноль:
// `until … sleep 30` может спать часами, и именно так и спали.
const UNBOUNDED = 1e9
function sleepBudget(cmd) {
  const c = String(cmd || '')
  const sleeps = [...c.matchAll(/\bsleep\s+(\d+(?:\.\d+)?)/g)].map((m) => Number(m[1]))
  if (!sleeps.length) return 0
  const longest = Math.max(...sleeps)
  const loop = /\b(until|while)\b/.test(c) || /\bfor\b[^\n]*\bin\b/.test(c)
  if (!loop) return longest
  const seq = c.match(/\bseq\s+1\s+(\d+)/)
  const times = c.match(/\{\s*1\s*\.\.\s*(\d+)\s*\}/)
  const turns = seq ? Number(seq[1]) : times ? Number(times[1]) : null
  if (!turns) return UNBOUNDED // цикл без видимой границы — спать может сколько угодно
  return turns * longest
}

