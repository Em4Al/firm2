// Линтер движка. Правило здесь ровно одно содержательное — `no-undef`, и поставлен он
// именно под него.
//
// 01.10.2026 я дважды за день привёз в живые проекты обращение к тому, чего нет:
// удалённую константу (`devGroup is not defined`) и забытый импорт. Оба дефекта нашлись
// прогонами сборки по пять миллионов токенов — то есть самым дорогим из возможных
// способов найти опечатку. `no-undef` находит этот класс целиком и статически, не
// исполняя код: обращение в неисполненной ветке он видит так же, как в исполненной. Этого
// не умеет ни `node --check` (он про синтаксис), ни рубеж `preflight.mjs` (он про
// исполнение).
//
// Стиля здесь нет намеренно. Движок пишется и правится в основном агентами, по разбору
// дефектов; замечания про кавычки и отступы в таком потоке только разбавляют сигнал. То
// немногое, что добавлено к `no-undef`, — тоже ловушки, а не вкус.
//
// Запуск: `npm run lint`. Он же шаг 0 рубежа (`node firm2/scripts/preflight.mjs`) и он же
// хук `.githooks/pre-commit` — секунда на коммит, зато обращение к тому, чего нет, не
// уезжает в проекты через `scripts/`, где версии нет и правка доезжает мгновенно.
// Про установку зависимостей на этой машине — ADR-0010.
import js from '@eslint/js'
import globals from 'globals'

const rules = {
  ...js.configs.recommended.rules,
  // Ради чего всё и поставлено.
  'no-undef': 'error',
  // Тоже про «обращение к тому, чего нет», только в другую сторону: объявил и забыл.
  // Аргументы не считаем — у hook-обработчиков сигнатура задана снаружи. Подчёркивание в
  // начале имени означает «знаю, что не нужно»: так помечен выброшенный при деструктуризации
  // `ts` в `writeEvent`, и выбросить его там — весь смысл строки.
  'no-unused-vars': ['error', { args: 'none', caughtErrors: 'none', varsIgnorePattern: '^_' }],
  // Молчаливые ловушки. `case` без `break` и присваивание в условии читаются как замысел,
  // а чаще всего это обрыв правки на середине.
  'no-fallthrough': 'error',
  'no-cond-assign': 'error',
  // Пустой `catch {}` в движке законен и используется осознанно: журнал важнее удачи с
  // git. Поэтому разрешён именно он, а не пустые блоки вообще.
  'no-empty': ['error', { allowEmptyCatch: true }],
  // Выключено осознанно, и это единственное выключенное правило из recommended. Оно
  // срабатывает на `let x = null` перед `try { x = ... } catch { x = null }` — в движке так
  // написан каждый разбор внешнего ответа (git, конфиг, транскрипт). Начальное значение
  // там избыточно формально, но читается как «по умолчанию ничего», и восемнадцать таких
  // замечаний утопили бы единственное настоящее, за которым линтер и ставился.
  'no-useless-assignment': 'off',
}

// Workflow — не модуль и не скрипт, а третье: рантайм Claude Code оборачивает тело файла
// в функцию и исполняет её. Поэтому в файле одновременно живут `export const meta` (нужен
// рантайму, чтобы прочитать имя и описание до запуска) и `return` на верхнем уровне. Ни
// один разборщик JS такую смесь не принимает: `sourceType: module` спотыкается на
// `return`, `script` — на `export`. Проверено всеми четырьмя комбинациями.
//
// Поэтому линтеру файл отдаётся завёрнутым ровно так, как его видит рантайм: `export`
// снимается, тело оборачивается в асинхронную функцию. Обёртка дописывается В ТЕ ЖЕ
// СТРОКИ — приставка в конец первой строки, хвост в конец последней, — и ни одного
// перевода строки не добавляется. Это не кокетство: номера строк в замечаниях остаются
// настоящими, иначе линтер указывал бы не туда, и ему перестали бы верить.
const workflowProcessor = {
  meta: { name: 'firm2-workflow', version: '1' },
  supportsAutofix: false,
  preprocess(text) {
    // `export const meta = …` превращается в `exports.meta = …`, а не в `const meta = …`.
    // Разница не косметическая: объявленная и никем не прочитанная константа — законное
    // замечание линтера о том, чего в исходнике нет (там `meta` читает рантайм), а
    // присваивание свойства читается как использование. Приписать `void meta` в хвост
    // нельзя: хвост идёт после `return` верхнего уровня, то есть недостижим, — и линтер
    // справедливо скажет уже об этом.
    const body = text.replace(/^export\s+const\s+meta\s*=/m, 'exports.meta =')
    return [{ text: `(async function () {${body}})()`, filename: 'wrapped.js' }]
  },
  postprocess(messages) {
    return messages.flat()
  },
}

export default [
  { ignores: ['node_modules/**'] },
  {
    // Скрипты движка: модули ESM, исполняются node-ом.
    files: ['firm2/scripts/**/*.mjs'],
    languageOptions: { ecmaVersion: 'latest', sourceType: 'module', globals: globals.node },
    rules,
  },
  {
    // Тесты — те же модули ESM, те же правила. Отдельный блок нужен из-за одного
    // послабления: в тестах естественно объявлять оснастку, которой пользуется не каждый
    // файл, и `no-unused-vars` на экспортируемых помощниках только мешал бы.
    files: ['firm2/tests/**/*.mjs'],
    languageOptions: { ecmaVersion: 'latest', sourceType: 'module', globals: globals.node },
    rules: { ...rules, 'no-unused-vars': ['error', { args: 'none', caughtErrors: 'none', varsIgnorePattern: '^_' }] },
  },
  {
    // Обвязка репозитория (`tools/`): те же правила, что у движка. В плагин она не входит
    // и в публичную копию не уезжает (`.gitattributes`), но `no-undef` нужен ей ровно так
    // же — `public-export.mjs` импортирует дюжину функций `node:fs` поимённо. Образец
    // терпит отсутствие каталога: в публичной копии `tools/` нет, а `npm run preflight`
    // там обязан проходить (флаг `--no-error-on-unmatched-pattern` в `package.json`).
    files: ['tools/**/*.mjs'],
    languageOptions: { ecmaVersion: 'latest', sourceType: 'module', globals: globals.node },
    rules,
  },
  {
    files: ['firm2/workflows/*.js'],
    processor: workflowProcessor,
  },
  {
    // Правила для завёрнутого workflow. `agent`, `parallel`, `pipeline`, `phase`, `log` и
    // `args` приходят из рантайма, а не из импортов, — для линтера это надо объявить,
    // иначе `no-undef` завалит файл целиком и его отключат вместе с пользой.
    // Без `**` в образце намеренно: шаблон `**/*.js/*.js` уводит minimatch в
    // переполнение стека, и ESLint падает целиком, не назвав причины.
    files: ['firm2/workflows/*.js/*.js'],
    languageOptions: {
      ecmaVersion: 'latest',
      sourceType: 'script',
      globals: {
        ...globals.node,
        agent: 'readonly',
        parallel: 'readonly',
        pipeline: 'readonly',
        phase: 'readonly',
        log: 'readonly',
        args: 'readonly',
      },
    },
    rules,
  },
]
